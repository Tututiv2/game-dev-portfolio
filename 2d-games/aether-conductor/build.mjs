// Bundles the ES modules in src/ into a single classic script (game.bundle.js)
// so the game runs by simply opening index.html via file:// (browsers block
// ES-module loading over file://). Sources stay modular for clarity; this just
// strips import/export and concatenates in dependency order inside one IIFE.
//
// Run:  node build.mjs   (re-run after editing any src file)

import { readFileSync, writeFileSync } from "node:fs";

const ORDER = [
  "src/core/rng.js",
  "src/core/math.js",
  "src/core/tick.js",
  "src/sim/grid.js",
  "src/sim/nodes.js",
  "src/sim/state.js",
  "src/content/research.js",
  "src/content/echoes.js",
  "src/content/secrets.js",
  "src/content/dimensions.js",
  "src/sim/dimension.js",
  "src/sim/mods.js",
  "src/sim/graph.js",
  "src/sim/heat.js",
  "src/sim/resonance.js",
  "src/sim/prestige.js",
  "src/sim/resources.js",
  "src/sim/autolayout.js",
  "src/render/particles.js",
  "src/render/scene.js",
  "src/render/minimap.js",
  "src/render/ui.js",
  "src/ui/devMenu.js",
  "src/core/save.js",
  "src/core/transfer.js",
  "src/main.js", // must be last: it executes on load
];

function strip(src) {
  return src
    // remove import statements (single or multi-line; they contain no inner ;)
    .replace(/^\s*import\s[^;]*;/gm, "")
    // remove `export { ... };` re-export statements
    .replace(/^\s*export\s*\{[^}]*\}\s*;?/gm, "")
    // turn `export function/const/let/class` into plain declarations
    .replace(/^(\s*)export\s+/gm, "$1");
}

// NB: no "use strict" — the bundle intentionally allows a couple of duplicate
// helper function declarations across modules (last wins), which strict forbids.
let out = `// AUTO-GENERATED by build.mjs — do not edit. Edit src/ then re-run.\n`;
out += `(function () {\n`;
for (const f of ORDER) {
  const code = strip(readFileSync(f, "utf8"));
  out += `\n// ===== ${f} =====\n${code}\n`;
}
out += `\n})();\n`;

writeFileSync("game.bundle.js", out);
console.log("Wrote game.bundle.js (" + out.length + " bytes from " + ORDER.length + " modules)");
