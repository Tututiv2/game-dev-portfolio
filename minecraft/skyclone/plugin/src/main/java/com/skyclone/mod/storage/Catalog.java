package com.skyclone.mod.storage;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * What every sack holds and how big every backpack is. Loaded from {@code data/storage/sacks.json} and
 * {@code backpacks.json} (generated by tools/gen/storage/gen_storage.py). No Bukkit: tests parse it directly.
 */
final class Catalog {

    record Weight(String group, int weight) {}

    record Family(String id, String name, String field, int order, List<String> sacks, List<String> contents,
                  Map<String, Weight> weights) {
        boolean weighted() { return !weights.isEmpty(); }
        /** The family's biggest sack item, used as its icon. */
        String icon() { return sacks.isEmpty() ? null : sacks.get(sacks.size() - 1); }
    }

    record Sack(String id, String family, long capacity, String tier) {}

    final List<Family> families = new ArrayList<>();
    final Map<String, Family> familyById = new LinkedHashMap<>();
    final Map<String, Sack> sacks = new LinkedHashMap<>();
    /** Item id -> families that hold it (an item can sit in two, e.g. Magma Cream: combat and lava fishing). */
    final Map<String, List<Family>> holders = new HashMap<>();
    final Set<String> quiver = new LinkedHashSet<>();

    final Map<String, Integer> backpackSlots = new LinkedHashMap<>();
    final Map<String, String> backpackBase = new LinkedHashMap<>();
    final Map<String, Map<String, String>> backpackColours = new LinkedHashMap<>();
    final Map<String, String> dyes = new LinkedHashMap<>();

    void loadSacks(InputStream in) throws java.io.IOException {
        if (in == null) return;
        try (Reader r = new InputStreamReader(in, StandardCharsets.UTF_8)) {
            JsonObject root = JsonParser.parseReader(r).getAsJsonObject();
            for (JsonElement fe : root.getAsJsonArray("families")) {
                JsonObject f = fe.getAsJsonObject();
                Map<String, Weight> w = new LinkedHashMap<>();
                if (f.has("weights")) {
                    for (Map.Entry<String, JsonElement> en : f.getAsJsonObject("weights").entrySet()) {
                        JsonObject o = en.getValue().getAsJsonObject();
                        w.put(en.getKey(), new Weight(o.get("group").getAsString(), o.get("weight").getAsInt()));
                    }
                }
                Family fam = new Family(f.get("id").getAsString(), f.get("name").getAsString(),
                        f.has("field") ? f.get("field").getAsString() : "", f.has("order") ? f.get("order").getAsInt() : families.size(),
                        strings(f, "sacks"), strings(f, "contents"), Collections.unmodifiableMap(w));
                families.add(fam);
                familyById.put(fam.id(), fam);
                for (String c : fam.contents()) holders.computeIfAbsent(c, k -> new ArrayList<>()).add(fam);
            }
            JsonObject s = root.getAsJsonObject("sacks");
            for (Map.Entry<String, JsonElement> en : s.entrySet()) {
                JsonObject o = en.getValue().getAsJsonObject();
                sacks.put(en.getKey(), new Sack(en.getKey(), o.get("family").getAsString(), o.get("capacity").getAsLong(),
                        o.has("tier") ? o.get("tier").getAsString() : "LARGE"));
            }
            if (root.has("quiver")) for (JsonElement q : root.getAsJsonArray("quiver")) quiver.add(q.getAsString());
        }
    }

    void loadBackpacks(InputStream in) throws java.io.IOException {
        if (in == null) return;
        try (Reader r = new InputStreamReader(in, StandardCharsets.UTF_8)) {
            JsonObject root = JsonParser.parseReader(r).getAsJsonObject();
            for (Map.Entry<String, JsonElement> en : root.getAsJsonObject("sizes").entrySet()) backpackSlots.put(en.getKey(), en.getValue().getAsInt());
            for (Map.Entry<String, JsonElement> en : root.getAsJsonObject("base").entrySet()) backpackBase.put(en.getKey(), en.getValue().getAsString());
            for (Map.Entry<String, JsonElement> en : root.getAsJsonObject("colours").entrySet()) {
                Map<String, String> m = new LinkedHashMap<>();
                for (Map.Entry<String, JsonElement> c : en.getValue().getAsJsonObject().entrySet()) m.put(c.getKey(), c.getValue().getAsString());
                backpackColours.put(en.getKey(), m);
            }
            for (Map.Entry<String, JsonElement> en : root.getAsJsonObject("dyes").entrySet()) dyes.put(en.getKey(), en.getValue().getAsString());
        }
    }

    private static List<String> strings(JsonObject o, String key) {
        List<String> out = new ArrayList<>();
        if (o.has(key)) for (JsonElement e : o.getAsJsonArray(key)) out.add(e.getAsString());
        return Collections.unmodifiableList(out);
    }

    // ---- questions ------------------------------------------------------------------------------

    boolean isSack(String id) { return id != null && sacks.containsKey(id); }

    boolean isBackpack(String id) { return id != null && backpackSlots.containsKey(id); }

    int backpackSlots(String id) { return id == null ? 0 : backpackSlots.getOrDefault(id, 0); }

    /** "SMALL", "MEDIUM"... for a backpack id (coloured or not). */
    String backpackSize(String id) {
        if (id == null) return null;
        for (String size : backpackBase.keySet()) if (id.equals(size + "_BACKPACK") || id.endsWith("_" + size + "_BACKPACK")) return size;
        return null;
    }

    List<Family> holdersOf(String itemId) { return itemId == null ? List.of() : holders.getOrDefault(itemId, List.of()); }

    boolean sackable(String itemId) { return !holdersOf(itemId).isEmpty(); }

    boolean isArrow(String itemId) { return itemId != null && quiver.contains(itemId); }

    /**
     * Add content ids to a family at runtime: the reference data lists no runes, so the Rune family is filled
     * from whatever items carry the {@code rune} tag once every module has registered. Returns how many were new.
     */
    int extend(String familyId, List<String> ids) {
        Family old = familyById.get(familyId);
        if (old == null || ids == null || ids.isEmpty()) return 0;
        List<String> contents = new ArrayList<>(old.contents());
        List<String> fresh = new ArrayList<>();
        for (String id : ids) if (id != null && !contents.contains(id)) { contents.add(id); fresh.add(id); }
        if (fresh.isEmpty()) return 0;
        Family nf = new Family(old.id(), old.name(), old.field(), old.order(), old.sacks(),
                Collections.unmodifiableList(contents), old.weights());
        families.replaceAll(f -> f == old ? nf : f);
        familyById.put(familyId, nf);
        for (List<Family> l : holders.values()) l.replaceAll(f -> f == old ? nf : f);
        for (String id : fresh) holders.computeIfAbsent(id, k -> new ArrayList<>()).add(nf);
        return fresh.size();
    }

    /** All distinct content ids. */
    Set<String> allContents() {
        Set<String> out = new LinkedHashSet<>();
        for (Family f : families) out.addAll(f.contents());
        return out;
    }
}
