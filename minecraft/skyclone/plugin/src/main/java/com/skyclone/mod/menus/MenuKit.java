package com.skyclone.mod.menus;

import com.google.gson.Gson;
import com.google.gson.reflect.TypeToken;
import com.skyclone.api.Sky;
import com.skyclone.api.feature.Features;
import com.skyclone.api.ui.Icons;
import com.skyclone.api.ui.Menu;
import com.skyclone.api.ui.Msg;
import com.skyclone.api.ui.Text;
import org.bukkit.Color;
import org.bukkit.Material;
import org.bukkit.Sound;
import org.bukkit.entity.Player;
import org.bukkit.inventory.ItemStack;
import org.bukkit.inventory.meta.ItemMeta;
import org.bukkit.inventory.meta.LeatherArmorMeta;
import org.bukkit.inventory.meta.PotionMeta;
import org.bukkit.inventory.meta.SkullMeta;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.lang.reflect.Type;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;

/** Shared helpers for every menu this module draws. */
final class MenuKit {

    private MenuKit() {}

    static final Gson GSON = new Gson();

    private static volatile Map<String, String> textures;

    /** Skull textures generated by tools/gen/menus/gen_menus.py. */
    static Map<String, String> textures() {
        Map<String, String> t = textures;
        if (t == null) {
            Type type = new TypeToken<Map<String, String>>() {}.getType();
            Map<String, String> loaded = readJson("textures.json", type);
            t = textures = loaded == null ? Map.of() : Collections.unmodifiableMap(loaded);
        }
        return t;
    }

    static <T> T readJson(String file, Type type) {
        try (InputStream in = Sky.plugin().getResource("data/menus/" + file)) {
            if (in == null) { Sky.log().warning("[menus] missing data/menus/" + file); return null; }
            return GSON.fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), type);
        } catch (Exception e) {
            Sky.log().warning("[menus] could not read data/menus/" + file + ": " + e);
            return null;
        }
    }

    static Material mat(String name, Material fallback) {
        if (name == null) return fallback;
        Material m = Material.matchMaterial(name);
        return m == null || !m.isItem() ? fallback : m;
    }

    /** Skull from textures.json when {@code textureKey} is known, else the material. */
    static ItemStack icon(String textureKey, String material, String name, List<String> lore) {
        String tex = textureKey == null ? null : textures().get(textureKey);
        if (tex != null) return Icons.skull(tex, name, lore);
        return Icons.of(mat(material, Material.PAPER), name, lore);
    }

    static ItemStack icon(String textureKey, String material, String name, String... lore) {
        return icon(textureKey, material, name, List.of(lore));
    }

    /** Dyed leather piece for wardrobe-style icons. */
    static ItemStack leather(Material m, Color c, String name, List<String> lore) {
        ItemStack it = Icons.of(m, name, lore);
        if (it.getItemMeta() instanceof LeatherArmorMeta lm) { lm.setColor(c); it.setItemMeta(lm); }
        return it;
    }

    /** A potion icon tinted with a colour. */
    static ItemStack potion(Color c, String name, List<String> lore) {
        ItemStack it = Icons.of(Material.POTION, name, lore);
        if (it.getItemMeta() instanceof PotionMeta pm) { pm.setColor(c); it.setItemMeta(pm); }
        return it;
    }

    /**
     * A look-alike of a real item for display in a menu (profile viewer): same material, name, lore,
     * skull, colour and glint, but NONE of its data - no sky id, no uuid. Even if a client ever got
     * it out of a menu it would be a plain, worthless item, never a dupe of a unique one.
     */
    static ItemStack displayCopy(ItemStack real, List<String> extraLore) {
        if (real == null || real.getType().isAir()) return null;
        ItemStack out = new ItemStack(real.getType(), Math.max(1, Math.min(real.getAmount(), real.getMaxStackSize())));
        ItemMeta src = real.getItemMeta();
        ItemMeta dst = out.getItemMeta();
        if (src != null && dst != null) {
            if (src.hasDisplayName()) dst.displayName(src.displayName());
            List<net.kyori.adventure.text.Component> lore = src.lore() == null ? new ArrayList<>() : new ArrayList<>(src.lore());
            if (extraLore != null && !extraLore.isEmpty()) lore.addAll(Text.lines(extraLore));
            dst.lore(lore);
            if (src instanceof SkullMeta ss && dst instanceof SkullMeta ds && ss.getPlayerProfile() != null) {
                ds.setPlayerProfile(ss.getPlayerProfile());
            }
            if (src instanceof LeatherArmorMeta sl && dst instanceof LeatherArmorMeta dl) dl.setColor(sl.getColor());
            if (src instanceof PotionMeta sp && dst instanceof PotionMeta dp && sp.hasColor()) dp.setColor(sp.getColor());
            if (src.hasEnchants() || (src.hasEnchantmentGlintOverride() && src.getEnchantmentGlintOverride())) {
                dst.setEnchantmentGlintOverride(true);
            }
            Icons.hide(dst);
            out.setItemMeta(dst);
        }
        return out;
    }

    /** Inventory titles longer than 32 visible characters get clipped by some clients. */
    static String clip(String s) { return s == null ? "" : s.length() > 32 ? s.substring(0, 32) : s; }

    // ---- feedback ------------------------------------------------------------------------------

    static void click(Player p) {
        if (SettingsStore.on(p, SettingDefs.CLICK_SOUNDS)) p.playSound(p.getLocation(), Sound.UI_BUTTON_CLICK, 0.5f, 1.2f);
    }

    static void deny(Player p, String msg) { Msg.error(p, msg); }

    static void comingSoon(Player p, String what) {
        Msg.error(p, what + " is not available yet - it is coming soon!");
    }

    // ---- navigation ------------------------------------------------------------------------------

    /** Go Back at 48 to the SkyBlock Menu. */
    static Menu backToSkyMenu(Menu m) {
        return m.set(m.closeSlot() - 1, Icons.back("SkyBlock Menu"), c -> {
            click(c.player());
            Sky.service(Features.SkyMenu.class).open(c.player());
        });
    }

    // ---- text ------------------------------------------------------------------------------------

    /** Wrapped description in &amp;7. */
    static List<String> wrap(String text) { return Text.wrap("&7" + text, 34); }

    /** "Progress: 45.2%" + bar line + "1,234/5,000". */
    static List<String> progress(String label, double have, double need) {
        double f = need <= 0 ? 1 : Math.max(0, Math.min(1, have / need));
        List<String> out = new ArrayList<>();
        out.add("&7" + label + ": &e" + pct(f));
        out.add(Text.bar(f, 20) + " &e" + Text.commasInt(have) + "&6/&e" + Text.shortNum(need));
        return out;
    }

    static String pct(double fraction) {
        double v = Math.round(fraction * 1000) / 10.0;
        return (v == Math.rint(v) ? String.valueOf((long) v) : String.valueOf(v)) + "%";
    }

    /** Legacy level colour like core's tab list: 0 gray .. 480+ dark red. */
    static String levelColor(int level) {
        String[] c = {"&7", "&f", "&e", "&a", "&2", "&b", "&3", "&9", "&d", "&5", "&6", "&c", "&4"};
        int i = Math.max(0, Math.min(c.length - 1, level / 40));
        return c[i];
    }

    static String sbLevelTag(int level) { return "&8[" + levelColor(level) + level + "&8]"; }

    /** Rarity index (0 common ... 5 mythic) of a pet rarity string. */
    static int rarityIndex(String rarity) {
        if (rarity == null) return 0;
        return switch (rarity.trim().toUpperCase(java.util.Locale.ROOT)) {
            case "UNCOMMON" -> 1; case "RARE" -> 2; case "EPIC" -> 3; case "LEGENDARY" -> 4; case "MYTHIC" -> 5;
            default -> 0;
        };
    }

    /** "&amp;8[Lvl 23] &amp;6Bee" for the active pet, or null when none. */
    static String petLabel(Player p) {
        Features.Pets pets = Sky.service(Features.Pets.class);
        String type = pets.activeType(p);
        if (type == null || type.isEmpty()) return null;
        String rarity = pets.activeRarity(p);
        com.skyclone.api.item.Rarity r = com.skyclone.api.item.Rarity.parse(rarity);
        String name = petName(type, rarity);
        return "&8[Lvl " + Math.max(1, pets.activeLevel(p)) + "] " + r.code() + name;
    }

    /** Display name of a pet type (the pets module's item name wins; renamed pets stay renamed). */
    static String petName(String type, String rarity) {
        String id = type + ";" + rarityIndex(rarity);
        try {
            var def = Sky.items().def(id);
            if (def != null && def.name != null && !def.name.isBlank()) {
                String n = Text.strip(def.name).replaceAll("^\\[Lvl [^\\]]*\\] ?", "").trim();
                if (!n.isEmpty()) return n;
            }
        } catch (Throwable ignored) {
            // a pets module that throws must never break a menu
        }
        return Text.titleCase(type);
    }
}
