package com.skyclone.mod.pets;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.google.gson.reflect.TypeToken;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.lang.reflect.Type;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

/**
 * Static pet data, generated by tools/gen/pets/gen_pets.py into resources/data/pets/. Pure Java:
 * the loader takes a resource opener so unit tests can read the same files from the source tree.
 */
public final class PetDefs {

    /** One ability of one pet at one rarity. Tokens map letters to indexes into that rarity's number arrays. */
    public static final class Ability {
        public String key;
        public String name;
        public List<String> lore = new ArrayList<>();
        public Map<String, Integer> tok = new LinkedHashMap<>();
        public List<JsonObject> fx = new ArrayList<>();
    }

    public static final class Tier {
        public Map<String, Double> s1 = new LinkedHashMap<>();
        public Map<String, Double> s100 = new LinkedHashMap<>();
        /** Stats the reference shows that this game has no stat for (Overbloom, Potato Fortune...). Display only. */
        public Map<String, Double> x1 = new LinkedHashMap<>();
        public Map<String, Double> x100 = new LinkedHashMap<>();
        public double[] n1 = new double[0];
        public double[] n100 = new double[0];
        public List<Ability> abilities = new ArrayList<>();

        public double num(int idx, int statLevel) {
            if (idx < 0 || idx >= n1.length || idx >= n100.length) return 0;
            return PetMath.lerp(n1[idx], n100[idx], statLevel);
        }
    }

    public static final class PetDef {
        public String id;
        public String name;
        public String skill;
        public List<String> rarities = new ArrayList<>();
        public int maxLevel = 100;
        public long[] extraLevels = new long[0];
        public Map<String, Integer> offsets;
        public double xpMult = 1;
        public String curve;
        public String skull;
        public boolean passive;
        public Map<String, Tier> tiers = new LinkedHashMap<>();

        public boolean has(String rarity) { return tiers.containsKey(rarity); }

        public String lowest() { return rarities.isEmpty() ? "COMMON" : rarities.get(0); }

        public String itemId(String rarity) { return id + ";" + PetMath.RARITIES.indexOf(rarity); }

        public String skillLabel() {
            return switch (skill == null ? "" : skill) {
                case "ALL" -> "All Skills";
                case "TAMING" -> "Taming";
                default -> skill.charAt(0) + skill.substring(1).toLowerCase();
            };
        }
    }

    public static final class HeldItem {
        public String id;
        public List<JsonObject> fx = new ArrayList<>();
        public String tune;
    }

    /** A pet skin (wave 5): cosmetic, bought with Bits at the Pet Sitter. */
    public static final class Skin {
        public String id;
        public String name;
        public List<String> pets = new ArrayList<>();
        public String rarity;
        public String skull;
        public long bits;

        public boolean fits(String petType) { return pets != null && pets.contains(petType); }
    }

    public static final class KatStep {
        public String pet;
        public String from;
        public String to;
        public long coins;
        public long seconds;
        public List<String> items = new ArrayList<>();
    }

    public static final class Candy {
        public String id;
        public long xp;
        public boolean counts;
    }

    public static final class ShopEntry {
        public String id;
        public long coins;
        public List<String> items = new ArrayList<>();
    }

    public static final class Supply {
        public String id;
        public long coins;
    }

    public static final class Meta {
        public List<int[]> scoreTable = new ArrayList<>();
        public List<String[]> collector = new ArrayList<>();
        public Map<String, Integer> katTaming = new LinkedHashMap<>();
        public List<Candy> candies = new ArrayList<>();
        public List<ShopEntry> shop = new ArrayList<>();
        public List<Supply> supplies = new ArrayList<>();
        public Map<String, Long> skipItems = new LinkedHashMap<>();
    }

    // ---- the registry --------------------------------------------------------------------------

    public final Map<String, PetDef> pets = new LinkedHashMap<>();
    public final Map<String, HeldItem> held = new LinkedHashMap<>();
    public final Map<String, KatStep> kat = new LinkedHashMap<>();       // key PET:FROM
    public final Map<String, Candy> candies = new LinkedHashMap<>();
    public final Map<String, Skin> skins = new LinkedHashMap<>();
    /** island -> MATERIAL -> mining block tags (wave 5, data/pets/dig.json from mining's block table). */
    public final Map<String, Map<String, List<String>>> dig = new LinkedHashMap<>();
    public Meta meta = new Meta();
    public PetMath.Curve curve;

    private static final Gson GSON = new Gson();

    /** Load everything. {@code open} returns a stream for "pets.json" etc., or null when missing. */
    public static PetDefs load(Function<String, InputStream> open) {
        PetDefs d = new PetDefs();
        List<PetDef> list = read(open, "pets.json", new TypeToken<List<PetDef>>() {}.getType());
        if (list != null) for (PetDef p : list) d.pets.put(p.id, p);
        List<HeldItem> h = read(open, "held_items.json", new TypeToken<List<HeldItem>>() {}.getType());
        if (h != null) for (HeldItem x : h) d.held.put(x.id, x);
        List<KatStep> k = read(open, "kat.json", new TypeToken<List<KatStep>>() {}.getType());
        if (k != null) for (KatStep x : k) d.kat.put(x.pet + ":" + x.from, x);
        List<Skin> sk = read(open, "skins.json", new TypeToken<List<Skin>>() {}.getType());
        if (sk != null) for (Skin x : sk) if (x.id != null) d.skins.put(x.id, x);
        Map<String, Map<String, List<String>>> dg = read(open, "dig.json", new TypeToken<Map<String, Map<String, List<String>>>>() {}.getType());
        if (dg != null) d.dig.putAll(dg);
        Meta m = read(open, "meta.json", Meta.class);
        if (m != null) d.meta = m;
        for (Candy c : d.meta.candies) d.candies.put(c.id, c);
        JsonObject xp = read(open, "xp.json", JsonObject.class);
        long[] levels = new long[0];
        Map<String, Integer> offsets = new LinkedHashMap<>();
        if (xp != null) {
            JsonArray a = xp.getAsJsonArray("levels");
            levels = new long[a.size()];
            for (int i = 0; i < a.size(); i++) levels[i] = a.get(i).getAsLong();
            for (Map.Entry<String, JsonElement> e : xp.getAsJsonObject("offsets").entrySet()) offsets.put(e.getKey(), e.getValue().getAsInt());
        }
        d.curve = new PetMath.Curve(levels, offsets);
        return d;
    }

    private static <T> T read(Function<String, InputStream> open, String file, Type type) {
        try (InputStream in = open.apply(file)) {
            if (in == null) return null;
            try (Reader r = new InputStreamReader(in, StandardCharsets.UTF_8)) {
                return GSON.fromJson(JsonParser.parseReader(r), type);
            }
        } catch (java.io.IOException e) {
            return null;
        }
    }

    // ---- lookups -------------------------------------------------------------------------------

    public PetDef pet(String id) { return id == null ? null : pets.get(id); }

    /** "BEE;4" -> [BEE, LEGENDARY], or null when not a pet item id. */
    public String[] parseItemId(String itemId) {
        if (itemId == null) return null;
        int i = itemId.lastIndexOf(';');
        if (i <= 0) return null;
        PetDef d = pets.get(itemId.substring(0, i));
        if (d == null) return null;
        try {
            int r = Integer.parseInt(itemId.substring(i + 1));
            if (r < 0 || r >= PetMath.RARITIES.size()) return null;
            return new String[]{d.id, PetMath.RARITIES.get(r)};
        } catch (NumberFormatException e) {
            return null;
        }
    }

    public KatStep katStep(String pet, String from) { return kat.get(pet + ":" + from); }

    /** Tags of the mining block this material is on this island (empty when it is not a mining block there). */
    public List<String> digTags(String island, String material) {
        if (island == null || material == null) return List.of();
        Map<String, List<String>> m = dig.get(island);
        List<String> t = m == null ? null : m.get(material);
        return t == null ? List.of() : t;
    }

    public double totalXpFor(PetDef d, String rarity, int level) {
        return curve.totalFor(rarity, d.offsets, d.extraLevels, level);
    }

    public int levelOf(PetDef d, String rarity, double xp) {
        return curve.levelOf(rarity, d.offsets, d.extraLevels, d.maxLevel, xp);
    }

    public double maxXp(PetDef d, String rarity) {
        return totalXpFor(d, rarity, d.maxLevel);
    }
}
