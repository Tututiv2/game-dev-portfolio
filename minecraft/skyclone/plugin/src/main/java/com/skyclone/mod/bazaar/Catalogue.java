package com.skyclone.mod.bazaar;

import com.google.gson.Gson;
import com.google.gson.reflect.TypeToken;
import com.skyclone.api.Sky;
import com.skyclone.api.item.EnchantDef;
import com.skyclone.api.item.ItemCategory;
import com.skyclone.api.item.ItemDef;
import com.skyclone.api.ui.Text;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * What the Bazaar trades and how it is shelved: categories -> groups -> products, generated by
 * {@code tools/gen/bazaar/gen_bazaar.py} from the research snapshot (2,197 products). Only products whose id
 * EXISTS in {@code Sky.items()} at runtime (and is stackable) are "live" — every other module decides which items
 * the game has, the Bazaar only decides which of them it trades. Items tagged {@code bazaar} that the snapshot
 * does not know are added live into Oddities / Miscellaneous (or their enchant group, for books).
 */
public final class Catalogue {

    public static final class Category {
        public String id, name, icon, glass;
    }

    public static final class Group {
        public String category, key, name, icon;
        public List<String> titleIds = new ArrayList<>();
        public List<String> products = new ArrayList<>();
        /** Live products only (filled at postEnable). */
        public transient List<String> live = new ArrayList<>();
    }

    public static final class Product {
        public String id, category, group;
        public double ref, refBid, refAsk, npcSell, npcBuy;
        public long weekly;
        public boolean mm = true;
        /**
         * Which sides the market maker may quote (generator, from how trustworthy the snapshot price is):
         * null = both; "ask" = only the ask is believable, so it sells and bids no more than the NPC price;
         * "bid" = nothing to price it by but the NPC, so it only bids, at exactly the NPC price, and never sells.
         */
        public String mmSides;
        /**
         * Progression-gating material (generator, research s2.9 seeding trick): units per Merchant Guild drop, 0 =
         * not seeded. {@link #seedFor} = up to three early items it unlocks (display only; may not all exist here).
         */
        public int seed;
        public List<String> seedFor;
        public transient boolean live;
        /** Cheapest NPC shop price found in the live recipe registry (NPC_SHOP, coins only), 0 = none. */
        public transient double shopPrice;
        public transient boolean extra;
        /** Enchanted books: the enchant id and level (two level-N books combine into N+1), else null / 0. */
        public transient String bookEnchant;
        public transient int bookLevel;
    }

    /** enchant id -> level -> live book product id, for the market makers' book-ladder arbitrage caps. */
    public final Map<String, Map<Integer, String>> bookLadder = new LinkedHashMap<>();

    private static final class GroupsDoc {
        List<Category> categories = new ArrayList<>();
        List<Group> groups = new ArrayList<>();
    }

    public final Map<String, Category> categories = new LinkedHashMap<>();
    public final Map<String, Group> groups = new LinkedHashMap<>();   // key -> group (keys are unique across categories)
    public final Map<String, Product> products = new LinkedHashMap<>();
    public final Map<String, List<Group>> byCategory = new LinkedHashMap<>();
    public int dataProducts, liveProducts, extraProducts;

    public void load() {
        Gson gson = new Gson();
        GroupsDoc doc = read(gson, "groups.json", GroupsDoc.class);
        List<Product> rows = read(gson, "products.json", new TypeToken<List<Product>>() {}.getType());
        if (doc != null) {
            for (Category c : doc.categories) { categories.put(c.id, c); byCategory.put(c.id, new ArrayList<>()); }
            for (Group g : doc.groups) {
                groups.put(g.key, g);
                byCategory.computeIfAbsent(g.category, k -> new ArrayList<>()).add(g);
            }
        }
        if (rows != null) for (Product p : rows) products.put(p.id, p);
        dataProducts = products.size();
    }

    @SuppressWarnings("unchecked")
    private static <T> T read(Gson gson, String file, java.lang.reflect.Type type) {
        try (InputStream in = Sky.plugin().getResource("data/bazaar/" + file)) {
            if (in == null) { Sky.log().severe("[bazaar] missing data/bazaar/" + file); return null; }
            return (T) gson.fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), type);
        } catch (Exception e) {
            Sky.log().severe("[bazaar] could not read " + file + ": " + e);
            return null;
        }
    }

    /** Decide which products are live, now that every module has registered its items. */
    public void resolveLive() {
        liveProducts = 0;
        for (Product p : products.values()) {
            ItemDef d = Sky.items().def(p.id);
            p.live = d != null && !d.isUnique();
            if (p.live) liveProducts++;
        }
        // items other modules tagged "bazaar" that the snapshot does not list
        for (ItemDef d : Sky.items().all()) {
            if (d == null || d.id == null || !d.has("bazaar") || products.containsKey(d.id) || d.isUnique()) continue;
            if (d.has("enchanting_alias")) continue;
            Product p = new Product();
            p.id = d.id;
            p.extra = true;
            p.live = true;
            p.npcSell = d.npcSell;
            p.ref = d.npcSell > 0 ? d.npcSell * 1.5 : 0;
            // Nothing prices it but its NPC value: the market maker only bids that (no cheap source of the item).
            p.mm = d.npcSell > 0;
            p.mmSides = "bid";
            String ench = d.extra != null && d.extra.has("enchant") ? d.extra.get("enchant").getAsString() : null;
            if (ench != null || d.category == ItemCategory.ENCHANTED_BOOK) {
                p.category = "ENCHANTMENTS";
                p.group = "ENCH_" + (ench == null ? "OTHER" : ench.toUpperCase(Locale.ROOT));
            } else {
                p.category = "ODDITIES";
                p.group = "MISC";
            }
            Group g = groups.get(p.group);
            if (g == null) {
                g = new Group();
                g.category = p.category;
                g.key = p.group;
                g.name = p.group.equals("MISC") ? "Miscellaneous" : null;
                g.icon = p.id;
                groups.put(g.key, g);
                byCategory.computeIfAbsent(g.category, k -> new ArrayList<>()).add(g);
            }
            g.products.add(p.id);
            products.put(p.id, p);
            extraProducts++;
            liveProducts++;
        }
        for (Group g : groups.values()) {
            g.live = new ArrayList<>();
            for (String id : g.products) { Product p = products.get(id); if (p != null && p.live) g.live.add(id); }
        }
        bookLadder.clear();
        for (Product p : products.values()) {
            if (!p.live) continue;
            ItemDef d = Sky.items().def(p.id);
            if (d == null || d.extra == null || !d.extra.has("enchant")) continue;
            try {
                p.bookEnchant = d.extra.get("enchant").getAsString().toLowerCase(Locale.ROOT);
                p.bookLevel = d.extra.has("level") ? d.extra.get("level").getAsInt() : 1;
                bookLadder.computeIfAbsent(p.bookEnchant, k -> new java.util.HashMap<>()).put(p.bookLevel, p.id);
            } catch (RuntimeException ignored) {
                p.bookEnchant = null;
                p.bookLevel = 0;
            }
        }
    }

    public Product product(String id) { return id == null ? null : products.get(id); }

    public boolean isLive(String id) { Product p = product(id); return p != null && p.live; }

    public Collection<Product> liveProducts() {
        List<Product> out = new ArrayList<>();
        for (Product p : products.values()) if (p.live) out.add(p);
        return out;
    }

    /** Live groups of a category, in shelf order. */
    public List<Group> liveGroups(String category) {
        List<Group> out = new ArrayList<>();
        for (Group g : byCategory.getOrDefault(category, List.of())) if (!g.live.isEmpty()) out.add(g);
        return out;
    }

    // ---- names --------------------------------------------------------------------------------------------

    /** Plain display name of a product (no colour): the owning module's name, enchanted books by their enchant. */
    public static String plainName(String id) {
        ItemDef d = Sky.items().def(id);
        if (d == null) return Text.titleCase(id);
        String book = bookName(d);
        if (book != null) return book;
        return Text.strip(d.name == null ? Text.titleCase(id) : d.name);
    }

    /** Coloured display name (rarity colour). */
    public static String name(String id) {
        ItemDef d = Sky.items().def(id);
        if (d == null) return "&f" + Text.titleCase(id);
        return (d.rarity == null ? "&f" : d.rarity.code()) + plainName(id);
    }

    private static String bookName(ItemDef d) {
        if (d.extra == null || !d.extra.has("enchant")) return null;
        try {
            String e = d.extra.get("enchant").getAsString();
            int lv = d.extra.has("level") ? d.extra.get("level").getAsInt() : 1;
            EnchantDef ed = Sky.items().enchant(e);
            String n = ed != null && ed.name != null ? ed.name : Text.titleCase(e);
            return n + " " + Text.roman(lv);
        } catch (RuntimeException ex) {
            return null;
        }
    }

    public String groupName(Group g) {
        if (g.name != null && !g.name.isEmpty()) return g.name;
        if (g.key.startsWith("ENCH_")) {
            String e = g.key.substring(5).toLowerCase(Locale.ROOT);
            EnchantDef ed = Sky.items().enchant(e);
            return ed != null && ed.name != null ? ed.name : Text.titleCase(e);
        }
        List<String> names = new ArrayList<>();
        for (String id : g.titleIds) if (Sky.items().exists(id)) names.add(plainName(id));
        if (names.isEmpty() && !g.live.isEmpty()) names.add(plainName(g.live.get(0)));
        return names.isEmpty() ? Text.titleCase(g.key) : String.join(" & ", names);
    }

    public String iconId(Group g) {
        if (g.icon != null && isLive(g.icon)) return g.icon;
        return g.live.isEmpty() ? g.icon : g.live.get(0);
    }

    public Group groupOf(String productId) {
        Product p = product(productId);
        return p == null ? null : groups.get(p.group);
    }

    public Category category(String id) { return categories.get(id); }

    /** Products whose name or id contains every word of the query. */
    public List<String> search(String query, int max) {
        String[] words = query.toLowerCase(Locale.ROOT).trim().split("\\s+");
        List<String> exact = new ArrayList<>(), hits = new ArrayList<>();
        for (Product p : products.values()) {
            if (!p.live) continue;
            String n = plainName(p.id).toLowerCase(Locale.ROOT);
            String id = p.id.toLowerCase(Locale.ROOT).replace('_', ' ');
            boolean all = true;
            for (String w : words) if (!w.isEmpty() && !n.contains(w) && !id.contains(w)) { all = false; break; }
            if (!all) continue;
            if (n.equals(query.toLowerCase(Locale.ROOT).trim())) exact.add(p.id); else hits.add(p.id);
            if (exact.size() + hits.size() >= max) break;
        }
        exact.addAll(hits);
        return exact;
    }
}
