    public final Map<String, Row> byStone = new HashMap<>();
    public final Map<String, StarEntry> stars = new HashMap<>();
    public final Map<String, List<Slot>> slots = new HashMap<>();
    public Gems gems = new Gems();
    public final Map<String, String> categories = new HashMap<>();
    public final Map<String, Double> shop = new LinkedHashMap<>();
    public final Map<String, Enrich> enrichments = new LinkedHashMap<>();
    public final Map<String, String> npcSkins = new HashMap<>();

