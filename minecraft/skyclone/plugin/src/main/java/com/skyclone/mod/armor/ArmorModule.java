/**
 * Armor: every armour set the brief assigns us (546 pieces, 122 multi-piece sets), their recipes,
 * and every set bonus as code. Data is generated by tools/gen/armor/gen_armor.py.
 *
 * <p>Player: {@code /armor} (alias /sets, /armorsets) opens the set browser; {@code /armor me}
 * shows what you wear. Admin: {@code /sb armor ...}.
 */
public final class ArmorModule implements GameModule {

    private static ArmorSets SETS = new ArmorSets();

    static ArmorSets sets() { return SETS; }

    @Override public String id() { return "armor"; }

    @Override
    public void enable() {
        ArmorDials.register();
        SETS = ArmorSets.load(Sky.plugin().getResource("data/armor/sets.json"));
        int items = Sky.items().loadJson("armor", "items.json");
        int recipes = Sky.recipes().loadJson("armor", "recipes.json");
        // wave 5: non-armour items a bonus needs and no other module registers (the Great Spook Staff)
        Sky.items().loadJson("armor", "extras.json");
        Sky.log().info("[armor] " + items + " armor pieces, " + recipes + " recipes, " + SETS.all().size() + " sets/pieces");

        Sky.stats().addProvider("armor_sets", BonusStats::contribute);
        BonusCombat.register();
        Bukkit.getPluginManager().registerEvents(new BonusCombat(), Sky.plugin());
        BonusListener.register(new BonusListener());
        // wave 5: Young Blood's speed cap and Newton's Demise's attack-speed cap, for the wearer only
        Bukkit.getPluginManager().registerEvents(new CapBonuses(), Sky.plugin());
        CapBonuses.startSpeedTask();
        // wave 5, second pass: Peace Treaty, Spooky, Old Blood's Feather Falling, Bat Swarm, Nether Lord's obsidian,
        // and the "Magic Find vs" bonuses through core's per-target loot hook
        Bukkit.getPluginManager().registerEvents(new ExtraBonuses(), Sky.plugin());
        Bukkit.getPluginManager().registerEvents(new NetherLord(), Sky.plugin());
        ExtraBonuses.start();
        BatSwarm.start();
        NetherLord.start();
        Sky.loot().addMagicFindModifier("armor_sets", BonusCombat::magicFindVs);

        Sky.commands().register(SkyCommand.of("armor", "Browse every armor set and see your active set bonuses")
                .alias("armorsets", "sets").category("General").usage("[me|<category>|<set>]").playerOnly()
                .run((s, a) -> openFor((Player) s, a.length > 0 ? a[0] : null))
                .tab((s, a) -> a.length <= 1 ? completions(a.length == 0 ? "" : a[0]) : List.of()));

        Sky.commands().admin("armor", "give|list|info|open|counter|charges|bones ...",
                "Armor test tools: give <p> <set|item>, list [filter], info <p>, open <p> [me|cat|set], "
                        + "counter <p> <magma|yog|growth> <n>, charges <p> <n>, bones <p> <n>",
                ArmorModule::admin, (s, a) -> adminTab(a));

        ArmorSelfTests.register();
    }

    @Override
    public void postEnable() {
        // after every module's enable-time provider: reads the accumulated totals
        Sky.stats().addProvider("armor_sets_final", BonusStats::contributeFinal);
    }

    @Override
    public void disable() {
        // Breath raised by Respiration / Long Tuba must not outlive the plugin (reload, shutdown).
        for (org.bukkit.entity.Player p : org.bukkit.Bukkit.getOnlinePlayers()) {
            ArmorState.P st = ArmorState.peek(p.getUniqueId());
            if (st != null && st.airRaised) BonusListener.restoreAir(p);
        }
        CapBonuses.disable();
        ExtraBonuses.disable();
        Worn.clear();
        ArmorState.clear();
    }

    // =========================================================================== player command

    static void openFor(Player p, String arg) {
        if (arg == null || arg.isBlank()) { ArmorMenus.main(p).open(p); return; }
        String a = arg.toLowerCase(Locale.ROOT);
        if (a.equals("me") || a.equals("worn") || a.equals("bonuses")) { ArmorMenus.worn(p).open(p); return; }
        for (String cat : ArmorSets.CATEGORIES) {
            if (cat.equalsIgnoreCase(a) || ArmorMenus.categoryName(cat).equalsIgnoreCase(arg)) {
                ArmorMenus.category(p, cat, 0).open(p);
                return;
            }
        }
        ArmorSets.SetInfo s = SETS.get(a);
        if (s == null) {
            String set = SETS.setOf(arg.toUpperCase(Locale.ROOT));
            s = set == null ? null : SETS.get(set);
        }
        if (s == null) for (ArmorSets.SetInfo x : SETS.all()) if (Text.strip(x.name).equalsIgnoreCase(arg)) { s = x; break; }
        if (s == null) { Msg.error(p, "No armor set called '" + arg + "'. Try /armor to browse."); return; }
        ArmorMenus.set(p, s, s.category, 0).open(p);
    }

    static List<String> completions(String prefix) {
        List<String> out = new ArrayList<>();
        String pre = prefix.toLowerCase(Locale.ROOT);
        out.add("me");
        for (String c : ArmorSets.CATEGORIES) out.add(c.toLowerCase(Locale.ROOT));
        for (ArmorSets.SetInfo s : SETS.all()) if (s.isSet) out.add(s.id);
        out.removeIf(x -> !x.startsWith(pre));
        return out.size() > 60 ? out.subList(0, 60) : out;
    }

    // =========================================================================== admin

    static void admin(CommandSender s, String[] a) {
        if (a.length == 0) { s.sendMessage(Text.c("&e/sb armor give|list|info|open|counter|charges|bones")); return; }
        String sub = a[0].toLowerCase(Locale.ROOT);
        switch (sub) {
            case "list" -> {
                String f = a.length > 1 ? a[1].toLowerCase(Locale.ROOT) : "";
                int n = 0;
                for (ArmorSets.SetInfo x : SETS.all()) {
                    if (!f.isEmpty() && !x.id.contains(f) && !Text.strip(x.name).toLowerCase(Locale.ROOT).contains(f)
                            && !x.category.equalsIgnoreCase(f)) continue;
                    if (n++ < 80) s.sendMessage(Text.c("&7" + x.id + " &8| &f" + x.name + " &8| " + x.category + " | " + x.pieces.size()
                            + "pc" + (x.bonuses.isEmpty() ? "" : " &6" + x.bonuses.get(0).name)));
                }
                s.sendMessage(Text.c("&a" + n + " match(es)" + (n > 80 ? " (first 80 shown)" : "")));
            }
            case "give" -> {
                Player t = player(s, a, 1);
                if (t == null || a.length < 3) { if (t != null) s.sendMessage(Text.c("&cUsage: /sb armor give <player> <set|item>")); return; }
                List<String> ids = new ArrayList<>();
                ArmorSets.SetInfo x = SETS.get(a[2].toLowerCase(Locale.ROOT));
                if (x != null) ids.addAll(x.pieces);
                else if (Sky.items().exists(a[2].toUpperCase(Locale.ROOT))) ids.add(a[2].toUpperCase(Locale.ROOT));
                if (ids.isEmpty()) { s.sendMessage(Text.c("&cUnknown set or item: " + a[2])); return; }
                for (String id : ids) Sky.loot().give(t, id, 1, LootSource.ADMIN);
                s.sendMessage(Text.c("&aGave " + t.getName() + " " + String.join(", ", ids)));
            }
            case "info" -> {
                Player t = player(s, a, 1);
                if (t == null) return;
                Worn w = Worn.of(t);
                s.sendMessage(Text.c("&e" + t.getName() + " &7— " + BonusListener.where(t)));
                String[] slot = {"Head", "Chest", "Legs", "Feet"};
                for (int i = 0; i < 4; i++) {
                    ItemDef d = w.defs[i];
                    s.sendMessage(Text.c("&7" + slot[i] + ": " + (w.ids[i] == null ? "&8-" : "&f" + w.ids[i] + (d != null && d.setId != null ? " &8[" + d.setId + "]" : "")
                            + (w.usable[i] ? "" : " &c(requirements not met)"))));
                }
                for (ArmorSets.SetInfo x : SETS.all()) {
                    int n = w.pieces(x.id);
                    if (n > 0) s.sendMessage(Text.c("&7Set &f" + x.id + "&7: " + n + "/" + x.size() + (w.full(x.id) ? " &aFULL" : "")));
                }
                for (Stat st : Stat.values()) {
                    Map<String, Double> b = Sky.stats().breakdown(t, st);
                    double v = b.getOrDefault("armor_sets", 0.0), fv = b.getOrDefault("armor_sets_final", 0.0);
                    double pct = b.getOrDefault("armor_sets (%)", 0.0), mul = b.getOrDefault("armor_sets (x)", 0.0) + b.getOrDefault("armor_sets_final (x)", 0.0);
                    if (v != 0 || fv != 0 || pct != 0 || mul != 0) s.sendMessage(Text.c("&7  " + st.display + ": &a" + Text.commas(v)
                            + (fv != 0 ? " &7final &a" + Text.commas(fv) : "") + (pct != 0 ? " &7(+" + Text.commas(pct) + "%)" : "")
                            + (mul != 0 ? " &7(x " + Text.commas(mul) + ")" : "") + " &8total " + Text.commas(Sky.stats().get(t, st))));
                }
                ArmorState.P stt = ArmorState.of(t.getUniqueId());
                s.sendMessage(Text.c("&7State: bones " + stt.bones + ", howl " + stt.howl.size() + ", strong " + stt.strong.size()
                        + ", goblin int removed " + Text.commas(stt.goblinRemoved)));
                long nowMs = System.currentTimeMillis();
                s.sendMessage(Text.c("&7Wave 3: max air " + t.getMaximumAir() + " ticks" + (stt.airRaised ? " (raised)" : "")
                        + ", burning " + (stt.burningSince > 0 ? (nowMs - stt.burningSince) / 1000 + "s" : "no")
                        + ", last magmatic hit " + (stt.magmaticHit > 0 ? (nowMs - stt.magmaticHit) / 1000 + "s ago" : "never")
                        + ", last mythic hit " + (stt.mythicHit > 0 ? (nowMs - stt.mythicHit) / 1000 + "s ago" : "never")));
                s.sendMessage(Text.c("&7Wave 5: Fear " + Text.commas(Fear.total(t)) + ", " + CapBonuses.describe(t)
                        + ", blaze pet +" + Text.commas(BonusListener.blazePetPercent(t)) + "%"));
                s.sendMessage(Text.c("&7Wave 5b: " + ExtraBonuses.describe(t)));
            }
            case "open" -> {
                Player t = player(s, a, 1);
                if (t == null) return;
                openFor(t, a.length > 2 ? a[2] : null);
                s.sendMessage(Text.c("&aOpened the armor menu for " + t.getName()));
            }
            case "counter" -> {
                Player t = player(s, a, 1);
                if (t == null || a.length < 4) { if (t != null) s.sendMessage(Text.c("&cUsage: /sb armor counter <player> <magma|yog|growth> <n>")); return; }
                long n;
                try { n = Long.parseLong(a[3]); } catch (NumberFormatException e) { s.sendMessage(Text.c("&cNot a number: " + a[3])); return; }
                String key = switch (a[2].toLowerCase(Locale.ROOT)) {
                    case "magma" -> BonusListener.KEY_MAGMA;
                    case "yog" -> BonusListener.KEY_YOG;
                    case "growth" -> BonusListener.KEY_GROWTH;
                    default -> null;
                };
                if (key == null) { s.sendMessage(Text.c("&cCounter must be magma, yog or growth")); return; }
                int changed = 0;
                Worn w = Worn.of(t);
                for (int i = 0; i < 4; i++) {
                    if (w.ids[i] == null) continue;
                    boolean match = switch (key) {
                        case BonusListener.KEY_MAGMA -> "ARMOR_OF_MAGMA_CHESTPLATE".equals(w.ids[i]);
                        case BonusListener.KEY_YOG -> "ARMOR_OF_YOG_CHESTPLATE".equals(w.ids[i]);
                        default -> w.defs[i] != null && SetIds.GROWTH.equals(w.defs[i].setId);
                    };
                    if (!match) continue;
                    var stack = BonusListener.slotItem(t.getInventory(), i);
                    long val = key.equals(BonusListener.KEY_GROWTH) ? Math.min(100, n) : n;
                    Sky.items().update(stack, d -> d.extra.addProperty(key, val));
                    BonusListener.setSlotItem(t.getInventory(), i, stack);
                    changed++;
                }
                Sky.stats().invalidate(t);
                s.sendMessage(Text.c(changed > 0 ? "&aSet " + key + " = " + n + " on " + changed + " worn piece(s)" : "&cNo matching worn piece"));
            }
            case "charges" -> {
                Player t = player(s, a, 1);
                if (t == null || a.length < 3) return;
                int n = parseInt(a[2]);
                ArmorState.of(t.getUniqueId()).thunderSince = System.currentTimeMillis() - (long) n * ArmorDials.THUNDER_SECONDS.get() * 1000L;
                s.sendMessage(Text.c("&aThunder charges for " + t.getName() + " set to " + Math.min(n, ArmorDials.THUNDER_CAP.get())));
            }
            case "bones" -> {
                Player t = player(s, a, 1);
                if (t == null || a.length < 3) return;
                ArmorState.of(t.getUniqueId()).bones = Math.max(0, parseInt(a[2]));
                s.sendMessage(Text.c("&aBone Shield bones for " + t.getName() + " set to " + a[2]));
            }
            default -> s.sendMessage(Text.c("&cUnknown sub: " + sub));
        }
    }

    private static int parseInt(String v) {
        try { return Integer.parseInt(v); } catch (NumberFormatException e) { return 0; }
    }

    private static Player player(CommandSender s, String[] a, int idx) {
        if (a.length <= idx) {
            if (s instanceof Player p) return p;
            s.sendMessage(Text.c("&cName a player"));
            return null;
        }
        Player t = Bukkit.getPlayerExact(a[idx]);
        if (t == null) s.sendMessage(Text.c("&cPlayer not online: " + a[idx]));
        return t;
    }

    private static List<String> adminTab(String[] a) {
        if (a.length <= 1) return List.of("give", "list", "info", "open", "counter", "charges", "bones");
        if (a.length == 2 && !a[0].equalsIgnoreCase("list")) {
            List<String> out = new ArrayList<>();
            for (Player p : Bukkit.getOnlinePlayers()) out.add(p.getName());
            return out;
        }
        if (a.length == 3 && a[0].equalsIgnoreCase("give")) return completions(a[2]);
        if (a.length == 3 && a[0].equalsIgnoreCase("counter")) return List.of("magma", "yog", "growth");
        return List.of();
    }
}
