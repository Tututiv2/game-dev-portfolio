package com.skyclone.mod.materials;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.skyclone.api.Sky;
import com.skyclone.api.item.ItemDef;
import com.skyclone.api.item.Recipe;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.logging.Level;

/**
 * The materials data as shipped (generated by tools/gen/materials/gen_materials.py) plus what
 * actually happened at registration: which ids this module registered, which a specialist module
 * already owned, which plain vanilla defs were upgraded, which recipes went in or were skipped.
 */
public final class MaterialsCatalogue {

    /** Family order for menus. */
    public static final List<String> FAMILIES = List.of("farming", "mining", "combat", "foraging", "fishing", "blocks", "misc");

    private static final Gson GSON = new Gson();

    final Map<String, ItemDef> defs = new LinkedHashMap<>();
    final Map<String, List<String>> families = new LinkedHashMap<>();
    final Map<String, List<String>> chains = new LinkedHashMap<>();
    final Map<String, String> prev = new LinkedHashMap<>();
    final Map<String, String> familyOf = new LinkedHashMap<>();
    final List<Recipe> recipes = new ArrayList<>();
    final Map<String, int[]> collectionTiers = new LinkedHashMap<>();
    /** Item data files that were absent from the jar (should always be empty). */
    final List<String> missingFiles = new ArrayList<>();

    // ---- what registration did ------------------------------------------------------------
    final Set<String> registered = new LinkedHashSet<>();
    final Set<String> replacedVanilla = new LinkedHashSet<>();
    final Set<String> ownedElsewhere = new LinkedHashSet<>();
    final List<Recipe> registeredRecipes = new ArrayList<>();
    final Map<String, String> skippedRecipes = new LinkedHashMap<>();
    final Map<Recipe, String> originalUnlock = new LinkedHashMap<>();
    /** Wave 5: catalogue items whose NPC price the live sell cap lowered, with the price they had before. */
    final Map<String, Double> liveCapped = new LinkedHashMap<>();
    boolean loaded;

    /** Read every data file from the jar. Safe to call once; logs and keeps going on a bad file. */
    void load() {
        // items_integration.json: fallbacks the integrator added for ids other modules reference and nobody
        // registered (tools/gen/materials/gen_integration.py). Browsed with the "misc" family.
        List<String[]> files = new ArrayList<>();
        for (String f : FAMILIES) files.add(new String[]{f, f});
        files.add(new String[]{"integration", "misc"});
        for (String[] file : files) {
            String fam = file[1];
            JsonElement el = read("data/materials/items_" + file[0] + ".json");
            if (el == null || !el.isJsonArray()) {
                // Loud, not silent: a missing items_integration.json once dropped X/Y/Z & co. and nothing said so.
                missingFiles.add("items_" + file[0] + ".json");
                Sky.log().warning("[materials] data file missing or not an array: items_" + file[0] + ".json");
                continue;
            }
            for (JsonElement e : el.getAsJsonArray()) {
                try {
                    ItemDef d = GSON.fromJson(e, ItemDef.class);
                    if (d == null || d.id == null || d.id.isBlank()) continue;
                    if (d.extra == null) d.extra = new JsonObject();
                    if (defs.putIfAbsent(d.id, d) != null) continue;   // first file wins; never list an id twice
                    familyOf.putIfAbsent(d.id, fam);
                    families.computeIfAbsent(fam, k -> new ArrayList<>()).add(d.id);
                } catch (RuntimeException ex) {
                    Sky.log().warning("[materials] bad item entry in items_" + fam + ".json: " + ex.getMessage());
                }
            }
        }
        JsonElement rs = read("data/materials/recipes.json");
        if (rs != null && rs.isJsonArray()) {
            for (JsonElement e : rs.getAsJsonArray()) {
                try {
                    Recipe r = GSON.fromJson(e, Recipe.class);
                    if (r == null || r.result == null) continue;
                    if (r.grid == null) r.grid = new String[9];
                    if (r.type == null) r.type = Recipe.Type.CRAFTING;
                    recipes.add(r);
                } catch (RuntimeException ex) {
                    Sky.log().warning("[materials] bad recipe entry: " + ex.getMessage());
                }
            }
        }
        JsonElement cat = read("data/materials/catalogue.json");
        if (cat != null && cat.isJsonObject()) {
            JsonObject o = cat.getAsJsonObject();
            if (o.has("chains")) for (Map.Entry<String, JsonElement> e : o.getAsJsonObject("chains").entrySet()) {
                List<String> l = new ArrayList<>();
                for (JsonElement x : e.getValue().getAsJsonArray()) l.add(x.getAsString());
                chains.put(e.getKey(), l);
                for (String x : l) prev.putIfAbsent(x, e.getKey());
            }
            if (o.has("collectionTiers")) for (Map.Entry<String, JsonElement> e : o.getAsJsonObject("collectionTiers").entrySet()) {
                JsonArray a = e.getValue().getAsJsonArray();
                int[] t = new int[a.size()];
                for (int i = 0; i < t.length; i++) t[i] = a.get(i).getAsInt();
                collectionTiers.put(e.getKey(), t);
            }
        }
        loaded = true;
        Sky.log().info("[materials] catalogue: " + defs.size() + " items, " + recipes.size() + " recipes, "
                + chains.size() + " compression chains");
    }

    private static JsonElement read(String path) {
        try (InputStream in = Sky.plugin().getResource(path)) {
            if (in == null) {
                Sky.log().warning("[materials] " + path + " missing from the jar");
                return null;
            }
            return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8));
        } catch (Exception e) {
            Sky.log().log(Level.WARNING, "[materials] could not read " + path, e);
            return null;
        }
    }

    // ---- queries ------------------------------------------------------------------------------

    public boolean has(String id) { return defs.containsKey(id); }

    public ItemDef dataDef(String id) { return defs.get(id); }

    public List<String> family(String fam) { return families.getOrDefault(fam, List.of()); }

    public String familyOf(String id) { return familyOf.get(id); }

    /** What this item compresses into (catalogue chains), possibly empty. */
    public List<String> next(String id) { return chains.getOrDefault(id, List.of()); }

    /** The catalogue item this one is compressed from, or null. */
    public String previous(String id) { return prev.get(id); }

    /** The bottom of the chain this item is part of. */
    public String root(String id) {
        String cur = id;
        for (int i = 0; i < 12; i++) {
            String p = previous(cur);
            if (p == null) return cur;
            cur = p;
        }
        return cur;
    }

    /** Every catalogue id that is the result of a compression (the "Compression Guide" list). */
    public List<String> compressedItems() {
        Set<String> out = new LinkedHashSet<>();
        for (String fam : FAMILIES) for (String id : family(fam)) if (previous(id) != null) out.add(id);
        return new ArrayList<>(out);
    }

    /** Chain roots (raw materials that compress into something), in family order. */
    public List<String> chainRoots() {
        Set<String> out = new LinkedHashSet<>();
        for (String fam : FAMILIES) for (String id : family(fam)) if (chains.containsKey(id) && previous(id) == null) out.add(id);
        return new ArrayList<>(out);
    }

    public List<Recipe> dataRecipesFor(String id) {
        List<Recipe> l = new ArrayList<>();
        for (Recipe r : recipes) if (id.equals(r.result)) l.add(r);
        return l;
    }

    public Set<String> registered() { return Collections.unmodifiableSet(registered); }
}
