    @Override public String id() { return "minions"; }

    @Override
    public void enable() {
        instance = this;
        cat = MinionCatalog.load(MinionsModule::reader);
        dials = new D();
        int n = Sky.items().loadJson("minions", "items.json");
        visuals = new MinionVisuals(this);
        manager = new MinionManager(this);
        menus = new MinionMenus(this);
        loadAliases();

        Sky.items().addLoreContributor("minions", new LoreContributor() {
            @Override public Section section() { return Section.BEFORE_FOOTER; }
            @Override public List<String> lines(ItemDef def, ItemData data) { return minionLore(def, data); }
        });
        Sky.requirements().register("minion", new MinionRequirement());
        Bukkit.getPluginManager().registerEvents(new MinionListener(this), Sky.plugin());
        MinionCommands.register(this);
        MinionSelfTests.register(this);
        Sky.sidebar().tabWidget("minions", 160, this::tabLines);
        Sky.stats().addProvider("minions.beacon", manager::contributeBeaconStat);

        // Recipes go in on the FIRST tick: materials registers the enchanted ingredients in postEnable, and
        // this task (scheduled in enable) runs before crafting's first-tick fill-in, so ours win.
        Bukkit.getScheduler().runTask(Sky.plugin(), this::registerRecipes);
        long period = Math.max(1, dials.tickSeconds.get()) * 20L;
        Bukkit.getScheduler().runTaskTimer(Sky.plugin(), () -> safe("tick", manager::tick), 40L, period);
        Bukkit.getScheduler().runTaskTimer(Sky.plugin(), () -> safe("animate", manager::animate), 60L, 10L);
        Bukkit.getScheduler().runTaskTimer(Sky.plugin(), () -> safe("bodies", manager::ensureStands), 50L, 40L);
        Sky.log().info("[minions] " + cat.types.size() + " types, " + n + " items, " + cat.fuels.size() + " fuels, "
                + cat.upgrades.size() + " upgrades/attachments");
    }

    @Override
    public void postEnable() {
        // A minion named after its item follows whatever the item's owner called it (mining may rename Mithril).
        for (TypeDef t : cat.types()) {
            if (t.nameFromItem == null) continue;
            ItemDef src = Sky.items().def(t.nameFromItem);
            if (src == null || src.name == null) continue;
            String base = Text.strip(src.name).trim();
            if (base.isEmpty() || base.equals(t.name)) continue;
            t.name = base;
            for (var td : t.tiers) {
                ItemDef d = Sky.items().def(t.itemId(td.tier));
                if (d != null) d.name = base + " Minion " + Text.roman(td.tier);
            }
        }
    }

    @Override
    public void disable() {
        try { Sky.stats().removeProvider("minions.beacon"); } catch (Throwable ignored) { }
        try { manager.despawnAll(); } catch (Throwable ignored) { }
    }

    private static void safe(String what, Runnable r) {
        try { r.run(); } catch (Throwable t) { Sky.log().log(Level.WARNING, "[minions] " + what + " failed", t); }
    }

    static Reader reader(String file) {
        InputStream in = Sky.plugin().getResource("data/minions/" + file);
        return in == null ? null : new InputStreamReader(in, StandardCharsets.UTF_8);
    }

    // ---- recipes ------------------------------------------------------------------------------------

    private void loadAliases() {
        // core's alias file maps modern Material names to the reference ids ("WOODEN_PICKAXE" -> "WOOD_PICKAXE");
        // inverted, it turns a reference id nobody registered back into the vanilla item every player has.
        try (InputStream in = Sky.plugin().getResource("data/core-items/vanilla_aliases.json")) {
            if (in == null) return;
            Map<String, List<String>> m = new Gson().fromJson(new InputStreamReader(in, StandardCharsets.UTF_8),
                    new TypeToken<Map<String, List<String>>>() {}.getType());
            for (Map.Entry<String, List<String>> e : m.entrySet())
                for (String legacy : e.getValue()) aliasToModern.putIfAbsent(legacy, e.getKey());
        } catch (Exception e) {
            Sky.log().log(Level.FINE, "[minions] no alias file", e);
        }
    }

    /** Tier I minion recipes are built around a wooden tool; the core alias file misses some of the 1.8 names. */
    private static final Map<String, String> LEGACY_TOOLS = Map.of("WOOD_SPADE", "WOODEN_SHOVEL", "WOOD_PICKAXE", "WOODEN_PICKAXE",
            "WOOD_AXE", "WOODEN_AXE", "WOOD_HOE", "WOODEN_HOE", "WOOD_SWORD", "WOODEN_SWORD");

    /** A reference id, or its vanilla equivalent when the reference id is not registered. */
    String resolveId(String id) {
        if (Sky.items().exists(id)) return id;
        String modern = aliasToModern.get(id);
        if (modern == null) modern = LEGACY_TOOLS.get(id);
        if (modern != null && Sky.items().exists(modern)) return modern;
        Material m = Material.matchMaterial(id);
        if (m != null && Sky.items().exists(m.name())) return m.name();
        return null;
    }

    void registerRecipes() {
        List<Recipe> list;
        try (Reader r = reader("recipes.json")) {
            list = new Gson().fromJson(r, new TypeToken<List<Recipe>>() {}.getType());
        } catch (Exception e) {
            Sky.log().log(Level.SEVERE, "[minions] cannot read recipes.json", e);
            return;
        }
        recipesSkipped.clear();
        recipesRegistered = 0;
        for (Recipe r : list) {
            if (r == null || r.result == null || !Sky.items().exists(r.result)) {
                recipesSkipped.add((r == null ? "?" : r.result) + ": result not registered");
                continue;
            }
            boolean ok = true;
            for (int i = 0; i < r.grid.length; i++) {
                String c = r.grid[i];
                if (c == null || c.isEmpty()) continue;
                String id = MinionManager.cellId(c);
                int amt = MinionManager.cellAmount(c);
                String real = resolveId(id);
                if (real == null) { ok = false; recipesSkipped.add(r.result + ": unknown ingredient " + id); break; }
                r.grid[i] = amt == 1 ? real : real + ":" + amt;
            }
            if (!ok) continue;
            if (r.station == null) r.station = "Minion";
            Sky.recipes().register(r);
            recipesRegistered++;
        }
        Sky.log().info("[minions] registered " + recipesRegistered + " recipes, skipped " + recipesSkipped.size()
                + (recipesSkipped.isEmpty() ? "" : " (/sb minions recipes)"));
    }

    // ---- lore, requirement, tab --------------------------------------------------------------------------

    List<String> minionLore(ItemDef def, ItemData data) {
        if (def == null || def.extra == null || !def.extra.has("minionType")) return List.of();
        List<String> l = new ArrayList<>();
        long gen = 0;
        boolean infused = false, loyal = false;
        if (data != null && data.extra != null) {
            try { if (data.extra.has("minionGenerated")) gen = data.extra.get("minionGenerated").getAsLong(); } catch (Exception ignored) { }
            try { if (data.extra.has("minionInfused")) infused = data.extra.get("minionInfused").getAsBoolean(); } catch (Exception ignored) { }
            try { if (data.extra.has("minionFreeWill")) loyal = data.extra.get("minionFreeWill").getAsBoolean(); } catch (Exception ignored) { }
        }
        l.add("&7Resources Generated: &b" + Text.commas(gen));
        if (infused) l.add("&eMithril Infused &7(&a+10% &7speed)");
        if (loyal) l.add("&6Free Will: &aLoyal &7(&a+10% &7speed)");
        l.add("");
        l.add("&eRight-click a block on your island to place!");
        return l;
    }

    private List<String> tabLines(Player p) {
        if (!Sky.profiles().isReady(p)) return List.of();
        MinionStore s = manager.store(p);
        if (s.placed.isEmpty()) return List.of();
        int full = 0;
        MinionManager.Env env = manager.env(p);
        for (MinionStore.Placed m : s.placed.values()) {
            TypeDef t = cat.type(m.type);
            if (t != null && MinionSim.isFull(cat, m, t, MinionSim.capacity(cat, m), env)) full++;
        }
        List<String> l = new ArrayList<>();
        l.add("&b&lMinions:");
        l.add(" Placed: &a" + s.working() + "&7/&a" + manager.slotsFor(p, s));
        int seated = s.placed.size() - s.working();
        if (seated > 0) l.add(" &7Seated: " + seated);
        if (full > 0) l.add(" &cFull: " + full);
        return l;
    }

    /** "minion:COBBLESTONE:4" crafted, "minion:uniques:50", "minion:slots:10". */
    final class MinionRequirement implements Requirements.Resolver {
        @Override public boolean check(Player p, String[] parts) {
            if (parts.length < 3 || !Sky.profiles().isReady(p)) return false;
            MinionStore s = manager.store(p);
            int n;
            try { n = Integer.parseInt(parts[2]); } catch (NumberFormatException e) { return false; }
            return switch (parts[1].toLowerCase()) {
                case "uniques" -> s.crafted.size() >= n;
                case "slots" -> manager.slotsFor(p, s) >= n;
                default -> s.crafted.contains(MinionStore.uniqueKey(parts[1].toUpperCase(), n));
            };
        }

        @Override public String describe(String[] parts) {
            if (parts.length < 3) return "&cMinion ?";
            return switch (parts[1].toLowerCase()) {
                case "uniques" -> "&a" + parts[2] + " Unique Minions";
                case "slots" -> "&a" + parts[2] + " Minion Slots";
                default -> {
                    TypeDef t = cat.type(parts[1].toUpperCase());
                    int n;
                    try { n = Integer.parseInt(parts[2]); } catch (NumberFormatException e) { n = 1; }
                    yield t == null ? "&a" + parts[1] + " Minion " + parts[2] : "&a" + t.name + " Minion " + Text.roman(n);
                }
            };
        }
    }
