package com.skyclone.mod.minions;

import com.google.gson.Gson;
import com.google.gson.reflect.TypeToken;

import java.io.IOException;
import java.io.Reader;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

/**
 * Everything the minion system knows that is DATA: the 61 minion types with their 11-12 tiers,
 * fuels, upgrades, compaction tables, collection XP and the slot table. Pure Java (no Bukkit), so the
 * unit tests load the very JSON the server ships. Generated by tools/gen/minions/gen_minions.py.
 */
public final class MinionCatalog {

    // ---- JSON shapes (Gson fills the fields) -------------------------------------------------------

    public static final class Drop {
        public String item;
        public double avg;
        public Drop() {}
        public Drop(String item, double avg) { this.item = item; this.avg = avg; }
    }

    public static final class TierDef {
        public int tier;
        public double tba;
        public int storage;
        /** Storage SLOTS (the reference counts storage in items, 64 per slot). */
        public int slots() { return Math.max(1, storage / 64); }
    }

    public static final class TypeDef {
        public String id, name, category, kind, visual, floor, color, skill, refName, unlock, tool, nameFromItem;
        public int maxTier;
        public int actionsPerHarvest = 2;
        public List<TierDef> tiers = new ArrayList<>();
        public List<Drop> drops = new ArrayList<>();

        public TierDef tier(int t) {
            for (TierDef d : tiers) if (d.tier == t) return d;
            return null;
        }
        public String itemId(int t) { return id + "_GENERATOR_" + t; }
        public int lowestTier() { return tiers.isEmpty() ? 1 : tiers.get(0).tier; }
        public int highestTier() { return tiers.isEmpty() ? 1 : tiers.get(tiers.size() - 1).tier; }
    }

    public static final class Specialty {
        public String item;
        public double avg;
        public double replace;
    }

    public static final class FuelDef {
        public String id;
        /** Real-time seconds one item lasts; 0 = never runs out. */
        public long seconds;
        public double speed;
        public double mult = 1;
        public boolean solar;
        public Map<String, Double> categoryBonus = new HashMap<>();
        public String onlyType;
        /** Wave 5: the fuel only powers minions of this category (Harvest Fair Participation Medal: FARMING). */
        public String onlyCategory;
        /** Wave 5: only one minion of the island may burn it at a time. */
        public boolean onePerProfile;
        /** Wave 5: one item per {@code every} seconds of BURN (not of harvests): the medal's tickets. */
        public PerSecond perSecond;
        public Specialty specialty;
        public List<Drop> extras = new ArrayList<>();

        public boolean infinite() { return seconds <= 0; }

        /** Does this fuel power a minion of that type at all? */
        public boolean powers(TypeDef t) {
            if (t == null) return false;
            if (onlyType != null && !onlyType.equals(t.id)) return false;
            return onlyCategory == null || onlyCategory.equals(t.category);
        }
    }

    public static final class Spread {
        public String item;
        public double perItem;
    }

    public static final class PerSecond {
        public String item;
        public double every;
    }

    public static final class UpgradeDef {
        public String id;
        /** upgrade | shipping | chest | infusion | crystal | stone | skin | beacon | power | freewill */
        public String slot;
        public Boolean smelt;
        public String compact;
        public Spread spread;
        public double speed;
        public int radius;
        public String requirement;
        public List<String> categories, types, kinds;
        public List<Drop> addDrops, setDrops;
        public Double output;
        public PerSecond perSecond;
        public double voidlingTierBonus;
        public boolean onePerProfile;
        public double sell;
        public int slots;
        public int fromTier, toTier;
        public String texture;
        public double perUniqueType;
        /** slot "power": real-time seconds one crystal powers a Beacon for. */
        public long seconds;
        /** slot "beacon": the Beacon tier (1-5). */
        public int tier;

        /** Can this upgrade go into a minion of that type? Null/empty lists mean "any". */
        public boolean appliesTo(TypeDef t) {
            if (types != null && !types.isEmpty() && !types.contains(t.id)) return false;
            if (categories != null && !categories.isEmpty() && !categories.contains(t.category)) return false;
            if (kinds != null && !kinds.isEmpty() && !kinds.contains(t.kind)) return false;
            return true;
        }
    }

    public static final class Rule {
        public String from;
        public int amount;
        public String to;
        public int count = 1;
    }

    public static final class SmeltRule {
        public String from, to;
    }

    public static final class Compaction {
        public List<Rule> block = new ArrayList<>();
        public List<Rule> enchanted = new ArrayList<>();
        public List<SmeltRule> smelt = new ArrayList<>();
    }

    public static final class XpEntry {
        public String skill;
        public double xp;
    }

    public static final class SlotRow {
        public int tier, minions, uniques;
    }

    public static final class Slots {
        public List<SlotRow> table = new ArrayList<>();
        public Map<String, Integer> sbxpPerTier = new HashMap<>();
        public int communityShopMax = 5;
    }

    // ---- the loaded catalogue ---------------------------------------------------------------------

    public final Map<String, TypeDef> types = new LinkedHashMap<>();
    public final Map<String, FuelDef> fuels = new LinkedHashMap<>();
    public final Map<String, UpgradeDef> upgrades = new LinkedHashMap<>();
    public final Map<String, Rule> blockRules = new LinkedHashMap<>();
    public final Map<String, Rule> enchantedRules = new LinkedHashMap<>();
    public final Map<String, String> smelt = new LinkedHashMap<>();
    public final Map<String, XpEntry> xp = new LinkedHashMap<>();
    public Slots slots = new Slots();
    public List<Map<String, Object>> rawRecipes = new ArrayList<>();

    /** Loads every file through {@code open} ("types.json" -> a Reader). Throws on a missing file. */
    public static MinionCatalog load(Function<String, Reader> open) {
        Gson g = new Gson();
        MinionCatalog c = new MinionCatalog();
        List<TypeDef> types = read(g, open, "types.json", new TypeToken<List<TypeDef>>() {});
        for (TypeDef t : types) {
            t.tiers.sort((a, b) -> Integer.compare(a.tier, b.tier));
            c.types.put(t.id, t);
        }
        List<FuelDef> fuels = read(g, open, "fuels.json", new TypeToken<List<FuelDef>>() {});
        for (FuelDef f : fuels) c.fuels.put(f.id, f);
        List<UpgradeDef> ups = read(g, open, "upgrades.json", new TypeToken<List<UpgradeDef>>() {});
        for (UpgradeDef u : ups) c.upgrades.put(u.id, u);
        Compaction comp = read(g, open, "compaction.json", new TypeToken<Compaction>() {});
        for (Rule r : comp.block) c.blockRules.put(r.from, r);
        for (Rule r : comp.enchanted) c.enchantedRules.put(r.from, r);
        for (SmeltRule s : comp.smelt) c.smelt.put(s.from, s.to);
        Map<String, XpEntry> xp = read(g, open, "xp.json", new TypeToken<Map<String, XpEntry>>() {});
        c.xp.putAll(xp);
        c.slots = read(g, open, "slots.json", new TypeToken<Slots>() {});
        return c;
    }

    private static <T> T read(Gson g, Function<String, Reader> open, String file, TypeToken<T> tt) {
        try (Reader r = open.apply(file)) {
            if (r == null) throw new IllegalStateException("missing data/minions/" + file);
            T v = g.fromJson(r, tt.getType());
            if (v == null) throw new IllegalStateException("empty data/minions/" + file);
            return v;
        } catch (IOException e) {
            throw new IllegalStateException("cannot read data/minions/" + file, e);
        }
    }

    // ---- lookups ----------------------------------------------------------------------------------

    public Collection<TypeDef> types() { return types.values(); }

    public TypeDef type(String id) { return id == null ? null : types.get(id); }

    /** "COBBLESTONE_GENERATOR_7" -> COBBLESTONE type, or null. */
    public TypeDef typeOfItem(String itemId) {
        if (itemId == null) return null;
        int i = itemId.lastIndexOf("_GENERATOR_");
        if (i <= 0) return null;
        return types.get(itemId.substring(0, i));
    }

    /** "COBBLESTONE_GENERATOR_7" -> 7, or 0. */
    public static int tierOfItem(String itemId) {
        if (itemId == null) return 0;
        int i = itemId.lastIndexOf("_GENERATOR_");
        if (i <= 0) return 0;
        try { return Integer.parseInt(itemId.substring(i + "_GENERATOR_".length())); }
        catch (NumberFormatException e) { return 0; }
    }

    public boolean isMinionItem(String itemId) {
        TypeDef t = typeOfItem(itemId);
        return t != null && t.tier(tierOfItem(itemId)) != null;
    }

    public UpgradeDef upgrade(String id) { return id == null ? null : upgrades.get(id); }

    public FuelDef fuel(String id) { return id == null ? null : fuels.get(id); }

    /** Deployables placed on the island itself (crystals and beacons), not into a minion. */
    public static boolean isDeployable(UpgradeDef u) {
        return u != null && ("crystal".equals(u.slot) || "beacon".equals(u.slot));
    }

    /** Placeable minions for a number of unique tiers crafted (research 02 section 4.3, before Community Shop). */
    public int placeableFor(int uniques) {
        int best = 0;
        for (SlotRow r : slots.table) if (uniques >= r.uniques) best = Math.max(best, r.minions);
        return best;
    }

    /** Uniques needed for the next slot, or -1 at the top of the table. */
    public int nextSlotAt(int uniques) {
        for (SlotRow r : slots.table) if (r.uniques > uniques) return r.uniques;
        return -1;
    }

    /** SkyBlock XP for crafting a new unique of this tier (research: I-VI 1, VII 2, VIII 3, IX 4, X 6, XI 12, XII 24). */
    public int sbxpForTier(int tier) {
        Integer v = slots.sbxpPerTier.get(String.valueOf(tier));
        return v == null ? 0 : v;
    }

    /** A compacted item resolved back to the raw item it was made from: {@code amount} raw per one compacted. */
    public record RawEquivalent(String item, long amount) {}

    /**
     * What one {@code id} is worth in raw items, following the Compactor / Ultra Compactor chains backwards
     * (ENCHANTED_COBBLESTONE -> 160 COBBLESTONE; ENCHANTED_SNOW_BLOCK -> 160 SNOW_BLOCK -> 640 SNOW_BALL).
     * Stops at the first item {@code isRaw} accepts (a collection item). Null when {@code id} is not a
     * compaction product, or when the chain never reaches an accepted item. Smelting is not reversed: a
     * smelted item is its own thing (IRON_INGOT is the collection; cactus green is not cactus).
     */
    public RawEquivalent rawEquivalent(String id, java.util.function.Predicate<String> isRaw) {
        if (id == null || isRaw.test(id)) return null;
        String cur = id;
        double mult = 1;
        for (int depth = 0; depth < 6; depth++) {
            Rule r = producerOf(cur);
            if (r == null || r.from == null || r.amount <= 0) return null;
            mult *= r.amount / (double) Math.max(1, r.count);
            cur = r.from;
            if (isRaw.test(cur)) return new RawEquivalent(cur, Math.round(mult));
        }
        return null;
    }

    private Map<String, Rule> producers;

    /** The compaction rule whose output is {@code to} (enchanted rules first: they are the Ultra Compactor's). */
    private Rule producerOf(String to) {
        if (producers == null) {
            Map<String, Rule> m = new HashMap<>();
            for (Rule r : enchantedRules.values()) if (r.to != null) m.putIfAbsent(r.to, r);
            for (Rule r : blockRules.values()) if (r.to != null) m.putIfAbsent(r.to, r);
            producers = m;
        }
        return producers.get(to);
    }

    /** Every item id the data references (drops, specialties, upgrade outputs, compaction, smelting, xp). */
    public java.util.Set<String> referencedItems() {
        java.util.Set<String> s = new java.util.TreeSet<>();
        for (TypeDef t : types.values()) for (Drop d : t.drops) s.add(d.item);
        for (FuelDef f : fuels.values()) {
            if (f.specialty != null) s.add(f.specialty.item);
            if (f.perSecond != null) s.add(f.perSecond.item);
            for (Drop d : f.extras) s.add(d.item);
        }
        for (UpgradeDef u : upgrades.values()) {
            if (u.spread != null) s.add(u.spread.item);
            if (u.perSecond != null) s.add(u.perSecond.item);
            if (u.addDrops != null) for (Drop d : u.addDrops) s.add(d.item);
            if (u.setDrops != null) for (Drop d : u.setDrops) s.add(d.item);
        }
        for (Rule r : blockRules.values()) { s.add(r.from); s.add(r.to); }
        for (Rule r : enchantedRules.values()) { s.add(r.from); s.add(r.to); }
        for (Map.Entry<String, String> e : smelt.entrySet()) { s.add(e.getKey()); s.add(e.getValue()); }
        return s;
    }
}
