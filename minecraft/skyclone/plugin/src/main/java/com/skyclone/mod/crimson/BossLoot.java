/**
 * Wave 5: who gets what when a mini-boss falls.
 *
 * <p>Before this, a mini-boss paid only its LAST hitter (core's MobKill goes to the killer), so a crowd fight on
 * a 50M-200M world boss paid one player and the rest walked away with nothing, and the reference's
 * faction-specific extras were "folded into the reputation bonus" (that is, they did not exist). Now:
 * <ul>
 *   <li>Every hit a player lands on a crimson mini-boss (or on a Cindermaw's split blazes) is booked on a
 *       per-fight ledger ({@link SkyEvents.Damage} at MONITOR, capped at the boss's health so an overkill
 *       does not count).</li>
 *   <li>When it dies, every player on the ledger who dealt {@code crimson.boss-loot-min-percent} of its health,
 *       is online and within range shares the kill: the boss's own drop table rolled with THEIR Magic Find, its
 *       coins and Combat XP (core already paid the killer), the kill count, the faction reputation (the rival
 *       champion pays more), the bits, and progress on an open BOSS quest.</li>
 *   <li>Pledged sharers add their <b>faction spoils</b> ({@link CrimsonRules#spoils}): their faction's key
 *       material from any mini-boss, the rival champion's own spoils when they bring down the champion their
 *       faction hunts, and a second roll at the Leviathan keys when the boss was on their quest board.</li>
 *   <li>Sharers who did not land the kill roll the boss's attribute shard at their own Charm Chance through
 *       {@code Features.Hunting} (hunting itself rolls it for the killer).</li>
 * </ul>
 * Every number of our own is in {@code factions.json} {@code boss_loot} (TUNE, generated by gen_tables.py).
 */
final class BossLoot implements Listener {

    /** One mini-boss fight: damage per player, the boss's max health, when it was last hit. */
    static final class Fight {
        final Map<UUID, Double> dealt = new LinkedHashMap<>();
        double max;
        long last;
    }

    private static final Map<UUID, Fight> FIGHTS = new HashMap<>();

    static CrimsonTables.BossLoot table() {
        CrimsonTables.BossLoot b = CrimsonModule.tables.factions.boss_loot;
        return b == null ? new CrimsonTables.BossLoot() : b;
    }

    // ---- the ledger -----------------------------------------------------------------------------------------

    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void onDamage(SkyEvents.Damage e) {
        DamageContext ctx = e.ctx;
        if (ctx == null || ctx.cancelled || ctx.victim == null) return;
        Player p = ctx.playerAttacker();
        if (p == null) return;
        LivingEntity v = ctx.victim;
        UUID key = v.getUniqueId();
        UUID parent = Bosses.parentOf(key);
        if (parent != null) key = parent;                      // a Cindermaw's split blaze: part of its fight
        else if (!isBoss(v)) return;
        double hp;
        try { hp = Sky.mobs().health(v); } catch (RuntimeException ex) { hp = 0; }
        double dmg = Double.isFinite(ctx.finalDamage) ? Math.max(0, ctx.finalDamage) : 0;
        if (hp > 0) dmg = Math.min(dmg, hp);
        if (dmg <= 0) return;
        book(key, p.getUniqueId(), dmg, parent == null ? safeMax(v) : 0);
    }

    /** Book {@code dmg} for {@code player} on the fight {@code boss}. Public to the package for the self-tests. */
    static void book(UUID boss, UUID player, double dmg, double max) {
        Fight f = FIGHTS.computeIfAbsent(boss, k -> new Fight());
        if (max > 0) f.max = Math.max(f.max, max);
        f.dealt.merge(player, dmg, Double::sum);
        f.last = System.currentTimeMillis();
    }

    /** A newcomer copy took over a boss fight ({@link Bosses#keepSingle}): its ledger comes along. */
    static void transfer(UUID from, UUID to) {
        Fight f = FIGHTS.remove(from);
        if (f == null) return;
        Fight t = FIGHTS.computeIfAbsent(to, k -> new Fight());
        t.max = Math.max(t.max, f.max);
        f.dealt.forEach((k, v) -> t.dealt.merge(k, v, Double::sum));
        t.last = Math.max(t.last, f.last);
    }

    /** Damage booked so far on one fight (self-tests, admin). */
    static Map<UUID, Double> ledger(UUID boss) {
        Fight f = FIGHTS.get(boss);
        return f == null ? Map.of() : new LinkedHashMap<>(f.dealt);
    }

    static int fights() { return FIGHTS.size(); }

    static void forget(UUID boss) { FIGHTS.remove(boss); }

    /** Every minute: drop ledgers of bosses that are gone (removed by an admin, unloaded) and untouched for 10 min. */
    static void sweep() {
        long cutoff = System.currentTimeMillis() - 600_000L;
        FIGHTS.entrySet().removeIf(en -> {
            org.bukkit.entity.Entity ent = Bukkit.getEntity(en.getKey());
            boolean gone = ent == null || !ent.isValid() || ent.isDead();
            return gone && en.getValue().last < cutoff;
        });
    }

    private static boolean isBoss(LivingEntity e) {
        MobDef d;
        try { d = Sky.mobs().defOf(e); } catch (RuntimeException ex) { return false; }
        return d != null && d.id != null && d.id.startsWith("crimson_") && d.has("boss");
    }

    private static double safeMax(LivingEntity e) {
        try { return Sky.mobs().maxHealth(e); } catch (RuntimeException ex) { return 0; }
    }

    // ---- the kill ---------------------------------------------------------------------------------------------

    /** A crimson mini-boss died (called by {@link Bosses#onKill}). Pays every sharer; returns how many shared. */
    static int bossDown(SkyEvents.MobKill e) {
        MobDef def = e.def;
        Fight f = FIGHTS.remove(e.mob.getUniqueId());
        Map<UUID, Double> dealt = f == null ? new LinkedHashMap<>() : new LinkedHashMap<>(f.dealt);
        double max = f != null && f.max > 0 ? f.max : safeMax(e.mob);
        if (max <= 0) max = def.health * Math.max(0.0001, CrimsonModule.D.bossHpScale.get());
        Player killer = e.killer;
        if (killer != null) dealt.putIfAbsent(killer.getUniqueId(), 0.0);
        boolean owned = Sky.mobs().owner(e.mob) != null;

        List<Map.Entry<UUID, Double>> ranked = CrimsonRules.ranking(dealt);
        double total = 0;
        for (double v : dealt.values()) total += v;
        double minPct = CrimsonModule.D.bossLootMinPercent.get();
        double range = Math.max(8, table().max_range);
        int shared = 0;
        List<String> podium = new ArrayList<>();
        for (int i = 0; i < ranked.size(); i++) {
            Map.Entry<UUID, Double> en = ranked.get(i);
            Player p = Bukkit.getPlayer(en.getKey());
            if (podium.size() < 3) podium.add((p == null ? "?" : p.getName()) + " &8(" + Text.shortNum(en.getValue()) + ")");
            if (p == null || !CrimsonModule.ready(p)) continue;
            boolean isKiller = p.equals(killer);
            if (owned && !isKiller) continue;                   // a private test fight pays its owner only
            if (!isKiller && (p.getWorld() != e.location.getWorld() || p.getLocation().distanceSquared(e.location) > range * range)) continue;
            if (!CrimsonRules.sharesKill(en.getValue(), max, minPct, isKiller)) {
                Msg.send(p, "&7You did not deal enough damage to " + def.name + " &7to share its spoils &8(needs "
                        + Text.commas(minPct) + "% of its health)&7.");
                continue;
            }
            pay(p, def, isKiller, en.getValue(), i + 1, ranked.size(), total);
            shared++;
        }
        announce(e, def, killer, podium);
        return shared;
    }

    /** Everything one sharer gets. The killer's drops/coins/XP were paid by core; everyone else's are paid here. */
    static void pay(Player p, MobDef def, boolean killer, double dmg, int place, int of, double total) {
        CrimsonData d = CrimsonModule.data(p);
        d.bossKills.merge(def.id, 1, Integer::sum);
        List<String> lines = new ArrayList<>();
        lines.add("&7Your damage: &c" + Text.commasInt(dmg) + " &8(#" + place + " of " + of
                + (total > 0 ? ", " + Math.round(dmg * 100 / total) + "%" : "") + ")");

        if (!killer && CrimsonModule.D.bossSharedLoot.get()) {
            if (def.coins > 0) Sky.economy().deposit(p, def.coins, "mob_kill:" + def.id + ":share");
            if (def.combatXp > 0) {
                try { Sky.service(SkillService.class).addXp(p, SkillType.COMBAT, def.combatXp, "crimson:miniboss"); }
                catch (RuntimeException ignored) { }
            }
            if (def.drops != null && !def.drops.isEmpty()) {
                try { Sky.loot().roll(p, def.drops, LootSource.MOB_DROP, Sky.loot().magicFind(p, def)); }
                catch (RuntimeException ex) { Sky.log().warning("[crimson] shared loot roll failed for " + def.id + ": " + ex); }
            }
            rollShard(p, def.id);
        }

        if (d.faction != null) {
            boolean champ = CrimsonRules.rivalChampion(CrimsonModule.tables.factions.factions, d.faction, def.id);
            Factions.addRep(p, d.faction, champ ? CrimsonModule.D.rivalBossRep.get() : CrimsonModule.D.bossRep.get(), def.name);
            boolean questOpen = Factions.bossQuestOpen(p, def.id);
            if (CrimsonModule.D.factionSpoils.get()) {
                CrimsonRules.Spoils sp = CrimsonRules.spoils(CrimsonModule.tables.factions, d.faction, def.id, questOpen);
                List<ItemStack> got = roll(p, sp.lines(), def);
                if (!got.isEmpty()) {
                    lines.add(Factions.color(d.faction) + Factions.display(d.faction) + " spoils"
                            + (sp.champion() ? " &6(rival champion!)" : "") + (sp.quest() ? " &e(quest target)" : "") + "&7:");
                    for (ItemStack it : got) lines.add(" &8+ &f" + it.getAmount() + "x " + itemName(it));
                }
            }
            Factions.bossKilled(p, def.id);
        }
        if (def.id.equals("crimson_magma_boss") || def.id.equals("crimson_ashfang")) {
            long bits = CrimsonModule.D.bossBits.get();
            if (bits > 0) Sky.economy().addBits(p, bits, "crimson: " + def.id + " kill");
        }
        Msg.box(p, "&c&l" + Text.strip(def.name).toUpperCase() + " DOWN!", lines);
        Msg.sound(p, Sound.ENTITY_PLAYER_LEVELUP, 0.8f);
    }

    /** Roll our own loot lines through core's loot service (Magic Find, RARE DROP lines, sacks, collections). */
    static List<ItemStack> roll(Player p, List<CrimsonTables.LootLine> table, MobDef def) {
        List<DropDef> drops = new ArrayList<>();
        for (CrimsonTables.LootLine l : table) {
            if (l == null || l.item == null || !Sky.items().exists(l.item) || l.chance <= 0) continue;
            drops.add(new DropDef(l.item, Math.max(1, l.min), Math.max(Math.max(1, l.min), l.max), Math.min(1.0, l.chance)));
        }
        if (drops.isEmpty()) return List.of();
        try {
            List<ItemStack> got = Sky.loot().roll(p, drops, LootSource.MOB_DROP, Sky.loot().magicFind(p, def));
            return got == null ? List.of() : got;
        } catch (RuntimeException ex) {
            Sky.log().warning("[crimson] faction spoils roll failed: " + ex);
            return List.of();
        }
    }

    /** A sharer who did not land the kill rolls the boss's attribute shard at their own Charm Chance. */
    static boolean rollShard(Player p, String bossId) {
        String shard = table().shards.get(bossId);
        if (shard == null || !Sky.items().exists(shard)) return false;
        Features.Hunting h = Sky.service(Features.Hunting.class);
        double charm;
        try { charm = h.attributeLevel(p, "stat:charm_chance"); } catch (RuntimeException ex) { return false; }
        if (!(charm > 0) || ThreadLocalRandom.current().nextDouble() * 100 >= charm) return false;
        try { h.addShards(p, shard, 1, "crimson_miniboss"); } catch (RuntimeException ex) { return false; }
        Msg.send(p, "&d&lCHARM! &7You caught a &d" + Text.strip(CUtil.name(shard)) + " &7from the fight.");
        return true;
    }

    private static String itemName(ItemStack it) {
        String id = Sky.items().idOf(it);
        return id == null ? it.getType().name() : CUtil.name(id);
    }

    private static void announce(SkyEvents.MobKill e, MobDef def, Player killer, List<String> podium) {
        String who = killer == null ? "the isle" : killer.getName();
        int secs = def.id.equals("crimson_magma_boss") ? CrimsonModule.D.magmaRespawn.get() : CrimsonModule.D.bossRespawn.get();
        String top = podium.isEmpty() ? "" : " &7Top damage: &f" + String.join("&7, &f", podium) + "&7.";
        Location at = e.location;
        if (at == null || at.getWorld() == null) return;
        for (Player o : at.getWorld().getPlayers())
            Msg.send(o, "&c&l" + Text.strip(def.name).toUpperCase() + " DOWN! &7Slain by &f" + who + "&7." + top
                    + " It returns in " + Text.duration(secs) + ".");
    }
}
