package com.secondwatch.client;

import com.secondwatch.content.SecondWatchContent;
import net.fabricmc.fabric.api.client.rendering.v1.EntityRendererRegistry;
import net.minecraft.client.renderer.entity.DrownedRenderer;
import net.minecraft.client.renderer.entity.EndermanRenderer;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.entity.HuskRenderer;
import net.minecraft.client.renderer.entity.SilverfishRenderer;
import net.minecraft.client.renderer.entity.SpiderRenderer;
import net.minecraft.client.renderer.entity.ZombieRenderer;
import net.minecraft.client.renderer.entity.state.EndermanRenderState;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import net.minecraft.client.renderer.entity.state.ZombieRenderState;
import net.minecraft.resources.Identifier;

/**
 * Custom skins for the bestiary.
 *
 * <p>Vanilla <em>geometry</em>, custom <em>texture</em>. That split is the whole
 * trick and it is worth being explicit about why, because the obvious complaint
 * is that these are reskinned mobs.
 *
 * <p>They are - and at the distance this mod is played at, that is the correct
 * call. A Follower is seen at forty blocks, in the dark, for two seconds, by
 * somebody who is frightened. Under those conditions the only things that
 * survive are silhouette and value: is it person-shaped, and is it darker or
 * lighter than the world behind it. Bespoke geometry costs weeks and none of it
 * arrives. A texture that turns a zombie into a featureless black shape with two
 * points of light costs an afternoon and completely changes what the player
 * thinks they saw.
 *
 * <p>So each renderer below is a vanilla one with exactly one method replaced.
 * The textures themselves are generated by remapping the vanilla files' own
 * luminance, which guarantees every UV region lands on the right body part.
 */
public final class MobRenderers {

    private static Identifier texture(String name) {
        return SecondWatchContent.id("textures/entity/" + name + ".png");
    }

    private MobRenderers() {
    }

    public static void register() {
        EntityRendererRegistry.register(SecondWatchContent.FOLLOWER, FollowerRenderer::new);
        EntityRendererRegistry.register(SecondWatchContent.WATCHER, WatcherRenderer::new);
        EntityRendererRegistry.register(SecondWatchContent.MIMIC, MimicRenderer::new);
        EntityRendererRegistry.register(SecondWatchContent.CRAWLER, CrawlerRenderer::new);
        EntityRendererRegistry.register(SecondWatchContent.TALL_ONE, TallOneRenderer::new);
        EntityRendererRegistry.register(SecondWatchContent.SWARM, SwarmRenderer::new);
    }

    /** A hole in the dark with two points of light in it. */
    public static class FollowerRenderer extends ZombieRenderer {
        private static final Identifier TEXTURE = texture("follower");

        public FollowerRenderer(EntityRendererProvider.Context context) {
            super(context);
        }

        @Override
        public Identifier getTextureLocation(ZombieRenderState state) {
            return TEXTURE;
        }
    }

    /** Bone dry and chalk pale, so it reads against dark stone rather than into it. */
    public static class WatcherRenderer extends HuskRenderer {
        private static final Identifier TEXTURE = texture("watcher");

        public WatcherRenderer(EntityRendererProvider.Context context) {
            super(context);
        }

        @Override
        public Identifier getTextureLocation(ZombieRenderState state) {
            return TEXTURE;
        }
    }

    /** Cold, and given a mouth - it is the one that talks. */
    public static class MimicRenderer extends DrownedRenderer {
        private static final Identifier TEXTURE = texture("mimic");

        public MimicRenderer(EntityRendererProvider.Context context) {
            super(context);
        }

        @Override
        public Identifier getTextureLocation(ZombieRenderState state) {
            return TEXTURE;
        }
    }

    /** The only warm thing in the bestiary, because it is one of two that bite. */
    public static class CrawlerRenderer extends SpiderRenderer<com.secondwatch.content.Crawler> {
        private static final Identifier TEXTURE = texture("crawler");

        public CrawlerRenderer(EntityRendererProvider.Context context) {
            super(context);
        }

        @Override
        public Identifier getTextureLocation(LivingEntityRenderState state) {
            return TEXTURE;
        }
    }

    /** Blacker than the night it is standing in. */
    public static class TallOneRenderer extends EndermanRenderer {
        private static final Identifier TEXTURE = texture("tall_one");

        public TallOneRenderer(EntityRendererProvider.Context context) {
            super(context);
        }

        @Override
        public Identifier getTextureLocation(EndermanRenderState state) {
            return TEXTURE;
        }
    }

    /** Pale, and there are a lot of them. */
    public static class SwarmRenderer extends SilverfishRenderer {
        private static final Identifier TEXTURE = texture("swarm");

        public SwarmRenderer(EntityRendererProvider.Context context) {
            super(context);
        }

        @Override
        public Identifier getTextureLocation(LivingEntityRenderState state) {
            return TEXTURE;
        }
    }
}
