"""ASS script assembly — BUILD_PROMPT.md §4.2.

Pure string work: captions + theme + reveal mode -> a .ass document. Fast enough
(milliseconds) that a style change can re-render the preview without ever going
near Whisper again.

Supports stacked LAYERS. Each layer gets its own [V4+ Styles] entry, and its
Dialogue events sit on their own ASS layer number so z-order is explicit: layer 0
draws first, later layers draw over it.

No Qt, no ffmpeg.
"""

from __future__ import annotations

from copy import deepcopy
from dataclasses import dataclass, field

from .model import Caption
from .reveal import DialogueEvent, render_card
from .themes import Animation, Theme

STYLE_FORMAT = (
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
    "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
    "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
)
EVENT_FORMAT = (
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
)

# Room between layers so a layer's gradient overlay can never sort above the
# next layer's base text.
LAYER_STRIDE = 10


@dataclass
class LayerRender:
    """One caption track ready to be written out."""

    captions: list[Caption]
    theme: Theme
    mode: str = "WORD_POP"
    anim: Animation = field(default_factory=Animation)

    def style_name(self, index: int) -> str:
        return f"Sub{index}"

    def gradient_style_name(self, index: int) -> str:
        return f"SubGrad{index}"


def ass_time(t: float) -> str:
    """ASS timestamps are H:MM:SS.cc — centiseconds, single-digit hour."""
    t = max(0.0, t)
    cs = int(round(t * 100))
    h, cs = divmod(cs, 360_000)
    m, cs = divmod(cs, 6_000)
    s, cs = divmod(cs, 100)
    return f"{h:d}:{m:02d}:{s:02d}.{cs:02d}"


def header(res_x: int, res_y: int) -> str:
    """PlayRes MUST equal the output resolution, or every size and margin is off
    by a scale factor — the #1 source of "why are my subtitles tiny" (§4.2)."""
    return "\n".join([
        "[Script Info]",
        "; Generated by SubtitleStudio",
        "ScriptType: v4.00+",
        f"PlayResX: {res_x}",
        f"PlayResY: {res_y}",
        "WrapStyle: 2",                 # we place our own \N breaks
        "ScaledBorderAndShadow: yes",   # or outlines go hairline at 4K
        "YCbCr Matrix: TV.709",
    ])


# ---------------------------------------------------------------------------
# Mode-specific theme adaptation
# ---------------------------------------------------------------------------


def adapt_theme(theme: Theme, mode: str) -> Theme:
    """ONE_WORD gets the screen to itself, so it centres and goes large (§4.3)."""
    if mode not in ("ONE_WORD",):
        return theme
    t = deepcopy(theme)
    if t.position == "bottom":
        t.position = "center"
    t.size_pct = max(t.size_pct, 12.0)
    t.inactive_opacity = 1.0
    return t


def _line_count(card: Caption) -> int:
    return max(1, len(card.lines()))


def _gradient_clip(theme: Theme, res_x: int, res_y: int, n_lines: int) -> str:
    """ASS has no gradient tag. The standard fake is two stacked copies of the
    text in different colours, the top one clipped to the upper half."""
    size = theme.font_size(res_y)
    block = size * 1.2 * n_lines
    margin_v = theme.margin_v_pct / 100 * res_y
    align = {"bottom": 2, "center": 5, "top": 8, "bottom_left": 1}.get(theme.position, 2)
    if align in (1, 2):
        top = res_y - margin_v - block
    elif align == 8:
        top = margin_v
    else:
        top = res_y / 2 - block / 2
    return rf"\clip(0,{round(top)},{res_x},{round(top + block / 2)})"


def _gradient_theme(theme: Theme) -> Theme:
    t = deepcopy(theme)
    t.base_colour = theme.gradient_colour
    t.active_colour = theme.gradient_colour
    return t


# ---------------------------------------------------------------------------
# Events
# ---------------------------------------------------------------------------


def build_layer_events(layer: LayerRender, index: int, res_x: int,
                       res_y: int) -> list[DialogueEvent]:
    theme = adapt_theme(layer.theme, layer.mode)
    base_layer = index * LAYER_STRIDE
    events: list[DialogueEvent] = []
    grad_theme = _gradient_theme(theme) if theme.gradient_colour else None

    for card in layer.captions:
        if not card.words:
            continue
        n_lines = _line_count(card)
        pos = "{" + theme.position_tag(res_x, res_y, n_lines) + "}"
        for ev in render_card(card, theme, layer.anim, pos, layer.mode):
            ev.layer = base_layer
            ev.style = layer.style_name(index)
            events.append(ev)

        if grad_theme is not None:
            clip = _gradient_clip(theme, res_x, res_y, n_lines)
            pos_top = "{" + theme.position_tag(res_x, res_y, n_lines) + clip + "}"
            for ev in render_card(card, grad_theme, layer.anim, pos_top, layer.mode):
                # The overlay MUST carry its own style: every reveal mode marks
                # non-active words with a bare \r, which resets to the event's
                # style — share the base style and the gradient vanishes.
                ev.layer = base_layer + 1
                ev.style = layer.gradient_style_name(index)
                events.append(ev)

    return events


def build_ass_layers(layers: list[LayerRender], res_x: int = 1920,
                     res_y: int = 1080) -> str:
    """Several caption tracks -> one .ass document."""
    parts = [header(res_x, res_y), "", "[V4+ Styles]", STYLE_FORMAT]

    active = [(i, lay) for i, lay in enumerate(layers) if lay.captions]
    for i, lay in active:
        styled = adapt_theme(lay.theme, lay.mode)
        parts.append(styled.style_line(res_x, res_y, lay.style_name(i)))
        if styled.gradient_colour:
            parts.append(_gradient_theme(styled).style_line(
                res_x, res_y, lay.gradient_style_name(i)))

    parts += ["", "[Events]", EVENT_FORMAT]

    events: list[DialogueEvent] = []
    for i, lay in active:
        events += build_layer_events(lay, i, res_x, res_y)

    for ev in events:
        if ev.end <= ev.start:
            continue
        text = ev.text.replace("\n", "")     # a literal newline would end the event
        parts.append(
            f"Dialogue: {ev.layer},{ass_time(ev.start)},{ass_time(ev.end)},"
            f"{ev.style},,0,0,0,,{text}"
        )

    return "\n".join(parts) + "\n"


def build_ass(
    captions: list[Caption],
    theme: Theme,
    anim: Animation | None = None,
    mode: str | None = None,
    res_x: int = 1920,
    res_y: int = 1080,
) -> str:
    """Single-layer convenience wrapper — used by the CLI and the unit tests."""
    return build_ass_layers(
        [LayerRender(captions, theme, mode or theme.default_reveal,
                     anim or Animation())],
        res_x, res_y,
    )


def build_events(captions, theme, anim, mode, res_x, res_y):
    """Back-compatible single-layer event list."""
    return build_layer_events(LayerRender(captions, theme, mode, anim), 0,
                              res_x, res_y)
