/* ============================================================================
   GENERATE src/render/treeGeom.js FROM THE BAKE-OFF'S OWN SOURCE.

   The grammar the breeder runs on and the grammar the GAME runs on have to be
   the same code, or a genome the owner picked in TREES.html grows into a
   different tree on the planet. So this wraps tools/trees/{geom,grow}.js as an
   ES module instead of anyone copying them by hand.

   Run:  node tools/gen_treegeom.mjs      (after any change to the grammar)
   ========================================================================= */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'tools', 'trees');
const read = f => fs.readFileSync(path.join(SRC, f), 'utf8');

let body = read('geom.js') + '\n' + read('grow.js');
// the bake-off runs off a global THREE; the game imports it
body = body.replace(/\bTHREE\./g, 'T.');

const out = `/* GENERATED by tools/gen_treegeom.mjs — do not edit by hand.
   The tree grammar, identical to the one TREES.html breeds on. A genome picked
   in the bake-off must grow into the SAME tree here, so this file is generated
   from tools/trees/geom.js + grow.js rather than copied.

   growFromCode('4E4A83...') -> BufferGeometry, base y=0, tip y=1, widest r=1,
   with the vec2 aPart attribute objectShader.js reads. */
import * as T from 'three';

${body}

const _CACHE = {};
export const isGenome = (s) => typeof s === 'string' && /^[0-9a-fA-F]{68}$/.test(s);
export function growFromCode(code) {
  if (_CACHE[code]) return _CACHE[code];
  const g = decGenome(code);
  if (!g) return null;
  return (_CACHE[code] = growTree(g));
}
export { decode as decodeGenome, describeGenome };
`;
fs.writeFileSync(path.join(ROOT, 'src', 'render', 'treeGeom.js'), out);
console.log(`  wrote src/render/treeGeom.js  (${(out.length / 1024).toFixed(0)} KB)`);
