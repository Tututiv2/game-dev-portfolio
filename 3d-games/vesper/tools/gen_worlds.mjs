/* ============================================================================
   GENERATE tools/trees/worlds.js FROM THE GAME'S OWN DATA.

   The breeder paints every tree from a world's palette, and a palette typed out
   by hand in a second place is a palette that drifts the first time anyone
   retunes a world. So this imports ARCHETYPES and OBJECT_KINDS and emits the
   table. Re-run it after any art change:  node tools/gen_worlds.mjs
   ========================================================================= */
import fs from 'fs';
import { ARCHETYPES } from '../src/world/archetypes.js';
import { OBJECT_KINDS } from '../src/world/objectKinds.js';

const rows = [];
for (const [key, A] of Object.entries(ARCHETYPES)) {
  const R = OBJECT_KINDS[key];
  if (!R) continue;                      // gas has no surface, on purpose
  const pick = (f, fb) => (f && A[f]) || A[fb] || A.mid;
  rows.push({
    key,
    name: A.name,
    blurb: A.blurb,
    trunk: pick(R.colFrom, 'hi'),        // exactly what the roster paints from
    tip:   pick(R.colTipFrom, 'mid'),
    glow:  A.emisB || A.emisC || A.mid,
    peak:  A.peak,
    accent: A.accent || A.peak,
    emis:  R.emissive,
    altTrunk: pick(R.alt && R.alt.colFrom, 'mid'),
    atmo:  A.atmo || '#4a8ab5',
    lo: A.lo, mid: A.mid, hi: A.hi,
    ambient: A.ambient,
    regions: R.regions || [key, key],
    label: R.label,
  });
}

const q = (s) => `'${s}'`;
const out = `/* GENERATED by tools/gen_worlds.mjs — do not edit by hand.
   Thirteen worlds, straight out of the game's own archetypes.js and
   objectKinds.js, so a tree bred here is painted in exactly the colours it
   would be painted in on the planet. \`gas\` is absent because it has no
   surface, which is a design decision and not an omission. */
var WORLDS = [
${rows.map(r => `  { key: ${q(r.key)}, name: ${q(r.name)}, label: ${q(r.label)},
    trunk: ${q(r.trunk)}, tip: ${q(r.tip)}, glow: ${q(r.glow)}, peak: ${q(r.peak)},
    accent: ${q(r.accent)}, altTrunk: ${q(r.altTrunk)}, emis: ${r.emis},
    atmo: ${q(r.atmo)}, lo: ${q(r.lo)}, mid: ${q(r.mid)}, hi: ${q(r.hi)},
    ambient: ${r.ambient}, regions: [${q(r.regions[0])}, ${q(r.regions[1])}],
    blurb: ${q(r.blurb.replace(/'/g, "\'"))} }`).join(',\n')},
];
var WORLD_BY = {};
for (var _w = 0; _w < WORLDS.length; _w++) WORLD_BY[WORLDS[_w].key] = WORLDS[_w];
`;
fs.writeFileSync('tools/trees/worlds.js', out);
console.log(`  wrote tools/trees/worlds.js — ${rows.length} worlds`);
for (const r of rows) console.log(`    ${r.key.padEnd(10)} ${r.name.padEnd(11)} trunk ${r.trunk}  tip ${r.tip}  glow ${r.glow}  emis ${r.emis}`);
